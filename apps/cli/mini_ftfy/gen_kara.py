#!/usr/bin/env python3
"""Appends the generated functions to mini_ftfy.kara, after the MARK line,
so the kata reads no files at run time. Every value is written in hex, so
the generated strings are plain ASCII.

- jobs_text(): data/jobs.tsv verbatim.
- regex_text(): the source of each regular expression ftfy uses, one
  "<name> <verbose 0|1> <bytes 0|1> <hex>" line each, read off the
  vendored library's compiled patterns. The port parses and compiles them
  itself (see "Regular expressions" in mini_ftfy.kara).
- codec_text(): the decoding tables of the single-byte codecs ftfy tries,
  "<name>" then 256 code points ("-" where the codec has no character), as
  Python's codecs module decodes each byte.
- html_text(): html.entities.html5 ("<name> <value>"), then html's table of
  replaced character references ("#<num> <value>") and the code points it
  drops ("!<lo> <hi>").
- unicode_text(): what the port needs from the Unicode database, from
  Python's unicodedata (Unicode 15.1): "D<cp> <c|k|x> <cps>" for each
  decomposition (canonical, compatibility, or canonical but excluded from
  composition; Hangul syllables are computed instead), "Q<lo> <hi> <ccc>"
  for each run of a nonzero combining class, and "P<lo> <hi>" (not
  printable), "W<lo> <hi>" (alphanumeric) and "9<lo> <hi>" (decimal digit)
  runs.

Run: python3 -I -B gen_kara.py"""
import codecs
import html
import os
import sys
import unicodedata
from html.entities import html5

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "vendor"))
from ftfy import badness, chardata, fixes  # noqa: E402
from ftfy.bad_codecs import utf8_variants  # noqa: E402

MARK = "\n// Generated by gen_kara.py from data/jobs.tsv.\n"
SRC = os.path.join(HERE, "mini_ftfy.kara")

PATTERNS = [
    ("HTML_ENTITY_RE", chardata.HTML_ENTITY_RE),
    ("ALTERED_UTF8_RE", chardata.ALTERED_UTF8_RE),
    ("LOSSY_UTF8_RE", chardata.LOSSY_UTF8_RE),
    ("C1_CONTROL_RE", chardata.C1_CONTROL_RE),
    ("UTF8_DETECTOR_RE", chardata.UTF8_DETECTOR_RE),
    ("SINGLE_QUOTE_RE", chardata.SINGLE_QUOTE_RE),
    ("DOUBLE_QUOTE_RE", chardata.DOUBLE_QUOTE_RE),
    ("A_GRAVE_WORD_RE", fixes.A_GRAVE_WORD_RE),
    ("ANSI_RE", fixes.ANSI_RE),
    ("ESCAPE_SEQUENCE_RE", fixes.ESCAPE_SEQUENCE_RE),
    ("BADNESS_RE", badness.BADNESS_RE),
    ("SPECIAL_BYTES_RE", utf8_variants.SPECIAL_BYTES_RE),
    ("CESU8_RE", utf8_variants.CESU8_RE),
]

CODECS = ["windows-1250", "windows-1251", "windows-1252", "windows-1253",
          "windows-1254", "windows-1257", "iso-8859-2", "mac-roman", "cp437"]


def text_fn(name, lines, chunk):
    out = ["fn %s() -> String {" % name, "    let mut s = String.new();"]
    buf = ""
    for ln in lines:
        assert all(32 <= ord(c) < 127 and c not in '"\\' for c in ln.replace("\t", " ")), ln
        buf += ln.replace("\t", "\\t") + "\\n"
        if len(buf) >= chunk:
            out.append('    s.push_str("%s");' % buf)
            buf = ""
    if buf:
        out.append('    s.push_str("%s");' % buf)
    out.append("    s")
    out.append("}")
    return "\n".join(out) + "\n"


def hexs(text):
    return " ".join("%x" % ord(c) for c in text)


def regex_lines():
    out = []
    for name, pat in PATTERNS:
        src = pat.pattern
        isbytes = isinstance(src, bytes)
        if isbytes:
            src = src.decode("latin-1")
        assert not (pat.flags & ~(64 | 32 | 256)), (name, pat.flags)
        verbose = 1 if pat.flags & 64 else 0
        out.append("%s %d %d %s" % (name, verbose, int(isbytes), src.encode("utf-8").hex()))
    return out


def codec_lines():
    out = []
    for name in CODECS:
        cells = []
        for byte in range(256):
            try:
                cells.append("%x" % ord(bytes([byte]).decode(name)))
            except UnicodeDecodeError:
                cells.append("-")
        out.append(name + " " + " ".join(cells))
    return out


def html_lines():
    out = ["%s %s" % (k, hexs(v)) for k, v in html5.items()]
    out += ["#%x %s" % (k, hexs(v)) for k, v in sorted(html._invalid_charrefs.items())]
    cps = sorted(html._invalid_codepoints)
    lo = prev = cps[0]
    for cp in cps[1:] + [None]:
        if cp is not None and cp == prev + 1:
            prev = cp
            continue
        out.append("!%x %x" % (lo, prev))
        if cp is not None:
            lo = prev = cp
    return out


def runs(tag, pred):
    out, start = [], None
    for cp in range(0x110001):
        v = cp < 0x110000 and pred(chr(cp))
        if v and start is None:
            start = cp
        elif not v and start is not None:
            out.append("%s%x %x" % (tag, start, cp - 1))
            start = None
    return out


def unicode_lines():
    out = []
    for cp in range(0x110000):
        if 0xAC00 <= cp <= 0xD7A3:
            continue
        d = unicodedata.decomposition(chr(cp))
        if not d:
            continue
        parts = d.split()
        if parts[0].startswith("<"):
            kind, parts = "k", parts[1:]
        elif unicodedata.normalize("NFC", chr(cp)) != chr(cp):
            kind = "x"
        else:
            kind = "c"
        out.append("D%x %s %s" % (cp, kind, " ".join(p.lower().lstrip("0") or "0" for p in parts)))
    start, prev = 0, 0
    for cp in range(0x110001):
        v = unicodedata.combining(chr(cp)) if cp < 0x110000 else 0
        if v != prev:
            if prev:
                out.append("Q%x %x %d" % (start, cp - 1, prev))
            start, prev = cp, v
    out += runs("P", lambda c: not c.isprintable())
    out += runs("W", lambda c: c.isalnum())
    out += runs("9", lambda c: c.isdecimal())
    return out


def main():
    with open(os.path.join(HERE, "data", "jobs.tsv"), encoding="utf-8") as fh:
        jobs = [ln for ln in fh.read().split("\n") if ln]
    with open(SRC, encoding="utf-8") as fh:
        src = fh.read()
    if MARK in src:
        src = src[: src.index(MARK)]
    src = src.rstrip("\n") + "\n" + MARK
    src += text_fn("jobs_text", jobs, 1)
    src += "\n" + text_fn("regex_text", regex_lines(), 1)
    src += "\n" + text_fn("codec_text", codec_lines(), 1)
    src += "\n" + text_fn("html_text", html_lines(), 2000)
    src += "\n" + text_fn("unicode_text", unicode_lines(), 2000)
    with open(SRC, "w", encoding="utf-8") as fh:
        fh.write(src)


main()
