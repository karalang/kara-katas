#!/usr/bin/env python3
"""Appends the generated functions to mini_pydicom.kara, after the MARK
line, so the program reads only the files it writes itself:

- jobs_text() is data/jobs.txt;
- inputs_text() the files mk.py writes (data/files.txt lists them), one
  "<path> <hex>" a line;
- dict_text(), uid_text() and private_text() the parts of pydicom's
  DicomDictionary, UID_dictionary and private_dictionaries the inputs can
  reach. A tag is kept when its bytes occur anywhere in an input, in either
  byte order (deflated inputs are inflated first) or when a job or the port
  names its keyword; a UID when its text occurs in an input or a job; a
  private creator's whole table when the creator's name occurs in an input.

Run: python3 -I -B gen_kara.py"""
import os
import struct
import sys
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
sys.modules['numpy'] = None
sys.path.insert(0, os.path.join(HERE, 'vendor'))
from pydicom._dicom_dict import DicomDictionary  # noqa: E402
from pydicom._uid_dict import UID_dictionary  # noqa: E402
from pydicom._private_dict import private_dictionaries  # noqa: E402

MARK = "\n// Generated by gen_kara.py from data/jobs.txt.\n"
SRC = os.path.join(HERE, "mini_pydicom.kara")

# Keywords mini_pydicom.kara itself looks up by name.
PORT_KEYWORDS = [
    'FileMetaInformationGroupLength', 'TransferSyntaxUID', 'SpecificCharacterSet',
    'PixelData', 'PixelRepresentation', 'BitsAllocated', 'PatientName', 'PatientID',
    'PatientBirthDate', 'OtherPatientIDs', 'StudyInstanceUID', 'SeriesInstanceUID',
    'StudyDate', 'StudyDescription', 'SeriesNumber', 'Modality', 'SeriesDescription',
    'InstanceNumber',
]
TS_UIDS = ['1.2.840.10008.1.2', '1.2.840.10008.1.2.1', '1.2.840.10008.1.2.2',
           '1.2.840.10008.1.2.4.50', '1.2.840.10008.1.2.1.99']


def text_fn(name, lines, chunk=2000):
    out = ["fn %s() -> String {" % name, "    let mut s = String.new();"]
    buf = ""
    for ln in lines:
        assert all(32 <= ord(c) < 127 and c not in '"\\{}' for c in ln), ln
        buf += ln + "\\n"
        if len(buf) >= chunk:
            out.append('    s.push_str("%s");' % buf)
            buf = ""
    if buf:
        out.append('    s.push_str("%s");' % buf)
    out.append("    s")
    out.append("}")
    return "\n".join(out) + "\n"


def esc(text):
    """Field text the Kara side reads back with unesc(): ~ escapes the
    characters a string literal or an f-string would treat specially."""
    for a, b in [('~', '~t'), ('\\', '~b'), ('"', '~q'), ('{', '~o'), ('}', '~c')]:
        text = text.replace(a, b)
    return text


def rle_hex(b):
    out = []
    i = 0
    while i < len(b):
        j = i
        while j < len(b) and b[j] == 0:
            j += 1
        if j - i >= 8:
            out.append("z%d." % (j - i))
            i = j
        else:
            out.append("%02x" % b[i])
            i += 1
    return "".join(out)


def inflated(data):
    """The dataset of a deflated file: raw deflate after the file meta,
    whose length its group length element gives."""
    start = 132 + 12 + struct.unpack('<L', data[140:144])[0]
    return [zlib.decompress(data[start:], -15)]


def main():
    with open(os.path.join(HERE, "data", "jobs.txt")) as f:
        jobs = [j for j in f.read().split("\n") if j]
    with open(os.path.join(HERE, "data", "files.txt")) as f:
        inputs = [ln for ln in f.read().split("\n") if ln]
    blobs = []
    files = []
    for name in inputs:
        with open(os.path.join(HERE, "data", name), "rb") as f:
            data = f.read()
        files.append("%s %s" % (name, rle_hex(data)))
        blobs.append(data)
        if b'1.2.840.10008.1.2.1.99' in data:
            blobs.extend(inflated(data))
    tags = set()
    for b in blobs:
        for i in range(len(b) - 3):
            for e in '<>':
                g, el = struct.unpack(e + 'HH', b[i:i + 4])
                t = g << 16 | el
                if t in DicomDictionary:
                    tags.add(t)
    words = set(' '.join(jobs).split(' ')) | set(PORT_KEYWORDS)
    for t, entry in DicomDictionary.items():
        if entry[4] in words:
            tags.add(t)
    dict_lines = []
    for t in sorted(tags):
        vr, vm, name, retired, kw = DicomDictionary[t]
        dict_lines.append('%08X|%s|%s|%s|%s' % (t, vr, vm, esc(name), kw))
    text = b'\n'.join(blobs) + '\n'.join(jobs + TS_UIDS).encode()
    uid_lines = []
    for uid in sorted(UID_dictionary):
        if uid.encode() in text:
            name, kind = UID_dictionary[uid][0], UID_dictionary[uid][1]
            uid_lines.append('%s|%s|%s' % (uid, esc(name), kind))
    priv_lines = []
    for creator in sorted(private_dictionaries):
        if any(creator.encode() in b for b in blobs):
            for key, (vr, vm, desc, _) in sorted(private_dictionaries[creator].items()):
                priv_lines.append('%s|%s|%s|%s' % (esc(creator), key, vr, esc(desc)))
    parts = [text_fn("jobs_text", jobs), text_fn("inputs_text", files),
             text_fn("dict_text", dict_lines), text_fn("uid_text", uid_lines),
             text_fn("private_text", priv_lines)]
    with open(SRC) as f:
        src = f.read()
    if MARK in src:
        src = src[:src.index(MARK)]
    with open(SRC, "w") as f:
        f.write(src + MARK + "\n" + "\n".join(parts))


main()
