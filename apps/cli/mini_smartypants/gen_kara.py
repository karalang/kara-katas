#!/usr/bin/env python3
"""Appends the generated functions to mini_smartypants.kara, after the MARK
line, so the kata reads only the files it writes itself.

- regex_text(): every regular expression the vendored library compiles,
  "<function>.<n> <flags> <hex>" a line, where n counts the distinct
  patterns each function uses in the order it first uses them and flags
  are re's (2 IGNORECASE, 16 DOTALL, 64 VERBOSE). They are read off the
  library by running each function once with re wrapped so it records
  what it is given, so the port compiles the library's own patterns.
  (_tags_to_skip_regex builds its pattern from the tag list each call;
  the port does that formatting itself.)
- unicode_text(): from Python's unicodedata (Unicode 15.1), the runs of
  code points that are alphanumeric ("W"), decimal digits ("9"),
  whitespace ("S") and not printable ("P"), for \\w, \\b, \\d, \\s and repr().
- jobs_text(): data/jobs.tsv verbatim, and posts_text(): the files under
  data/posts/ (as mk.py writes them), each "<name> <hex>".

Run: python3 -I -B gen_kara.py"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "vendor"))
import smartypants  # noqa: E402

MARK = "\n// Generated by gen_kara.py from data/jobs.tsv.\n"
SRC = os.path.join(HERE, "mini_smartypants.kara")

SEEN = []


class Recorder:
    def __getattr__(self, name):
        return getattr(re, name)

    def _note(self, pattern, flags):
        func = sys._getframe(2).f_code.co_name
        key = (func, pattern, int(flags))
        if key not in SEEN:
            SEEN.append(key)

    def compile(self, pattern, flags=0):
        self._note(pattern, flags)
        return re.compile(pattern, flags)

    def sub(self, pattern, repl, string, count=0, flags=0):
        self._note(pattern, flags)
        return re.sub(pattern, repl, string, count=count, flags=flags)

    def match(self, pattern, string, flags=0):
        self._note(pattern, flags)
        return re.match(pattern, string, flags)


def record():
    smartypants.re = Recorder()
    try:
        smartypants.smartypants("<b>'</b>\"x&quot;", smartypants.Attr.q | smartypants.Attr.w)
        for name in ["convert_quotes", "convert_backticks", "convert_single_backticks",
                     "convert_dashes", "convert_dashes_oldschool",
                     "convert_dashes_oldschool_inverted", "convert_ellipses",
                     "process_escapes", "_tokenize"]:
            getattr(smartypants, name)("x")
    finally:
        smartypants.re = re
    out = []
    count = {}
    for func, pattern, flags in SEEN:
        if func == "_tags_to_skip_regex":
            continue
        n = count.get(func, 0)
        count[func] = n + 1
        out.append("%s.%d %d %s" % (func, n, flags, pattern.encode("utf-8").hex()))
    return out


def runs(tag, pred):
    out, start = [], None
    for cp in range(0x110001):
        v = cp < 0x110000 and pred(chr(cp))
        if v and start is None:
            start = cp
        elif not v and start is not None:
            out.append("%s%x %x" % (tag, start, cp - 1))
            start = None
    return out


def text_fn(name, lines, chunk=2000):
    out = ["fn %s() -> String {" % name, "    let mut s = String.new();"]
    buf = ""
    for ln in lines:
        assert all(32 <= ord(c) < 127 and c not in '"\\{}' for c in ln.replace("\t", " ")), ln
        buf += ln.replace("\t", "\\t") + "\\n"
        if len(buf) >= chunk:
            out.append('    s.push_str("%s");' % buf)
            buf = ""
    if buf:
        out.append('    s.push_str("%s");' % buf)
    out.append("    s")
    out.append("}")
    return "\n".join(out) + "\n"


def main():
    parts = [text_fn("regex_text", record())]
    uni = (runs("W", lambda c: c.isalnum()) + runs("9", lambda c: c.isdecimal())
           + runs("S", lambda c: c.isspace()) + runs("P", lambda c: not c.isprintable()))
    parts.append(text_fn("unicode_text", uni))
    with open(os.path.join(HERE, "data", "jobs.tsv"), "rb") as f:
        jobs = f.read().decode("utf-8").split("\n")
    parts.append(text_fn("jobs_text", [j.encode("utf-8").hex() for j in jobs if j]))
    posts = os.path.join(HERE, "data", "posts")
    files = []
    for name in sorted(os.listdir(posts)):
        with open(os.path.join(posts, name), "rb") as f:
            files.append("%s %s" % (name, f.read().hex() or "-"))
    parts.append(text_fn("posts_text", files))
    with open(SRC) as f:
        src = f.read()
    if MARK in src:
        src = src[:src.index(MARK)]
    with open(SRC, "w") as f:
        f.write(src + MARK + "\n" + "\n".join(parts))


main()
