job("unparse", "json/ns.json", opts(namespaces={"a": "A", "b": "B"}, namespace_separator=":", pretty=True))
job("unparse", "json/config.json", opts(preprocessor="skip_admins", pretty=True, indent="  "))
job("unparse", "json/config.json", opts(preprocessor="upper"))
job("unparse", "json/list-root.json", opts(full_document=False))
job("unparse", "json/list-root.json", opts(full_document=False, pretty=True))
job("unparse", "json/two-roots.json", opts())
job("unparse", "json/two-roots.json", opts(full_document=False, pretty=True))
for d in ["bad-name.json", "bad-q.json", "bad-attr.json", "bad-nbsp.json", "bad-ns.json", "text-int.json", "text-list.json"]:
    job("unparse", "json/" + d, opts())
job("unparse", "json/list-root.json", opts(attr_prefix="", cdata_key="item"))

job("== reports")
job("s3report", "xml/s3-list.xml")
job("s3report", "xml/s3-one.xml")
job("feedreport", "xml/feed.xml")
job("gpxreport", "xml/ride.gpx")
