#!/usr/bin/env python3
"""Appends tables_text() and jobs_text() to mini_exifread.kara, after the
MARK line, so the kata reads no files at run time. tables_text() is the
vendored tag tables (exifread/tags), one line per tag or lookup entry:

  T <table> <tag> <name> n                 no formatter
  T <table> <tag> <name> d <dict>          a dict of value names
  T <table> <tag> <name> f <func>          a formatting function
  T <table> <tag> <name> s <table> <ifd>   a sub-IFD
  D <dict> <key> <name>

Run: python3 -I -B gen_kara.py"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "vendor"))
from exifread.tags import exif  # noqa: E402
from exifread.tags.makernote import apple, canon, casio, dji, fujifilm, nikon, olympus, sony  # noqa: E402

MARK = "\n// Generated by gen_kara.py from the vendored tag tables and data/jobs.tsv.\n"
SRC = os.path.join(HERE, "mini_exifread.kara")

# Table ids; mini_exifread.kara names them as constants.
TABLES = [
    exif.EXIF_TAGS, exif.GPS_TAGS, exif.INTEROP_TAGS, nikon.TAGS_OLD, nikon.TAGS_NEW,
    olympus.TAGS, casio.TAGS, sony.TAGS, fujifilm.TAGS, apple.TAGS, dji.TAGS, canon.TAGS,
] + [canon.OFFSET_TAGS[k] for k in (0x0001, 0x0002, 0x0004, 0x0012, 0x0026, 0x0093)]
FUNCS = {"make_string": "ms", "make_string_uc": "uc", "ev_bias": "ev", "special_mode": "sm",
         "convert_temp": "ct"}


def esc(s):
    out = []
    for c in s:
        if c == "\\":
            out.append("\\\\")
        elif c == '"':
            out.append('\\"')
        elif c == "\t":
            out.append("\\t")
        elif c == "\n":
            out.append("\\n")
        elif ord(c) < 32 or ord(c) == 127:
            out.append("\\x%02x" % ord(c))
        else:
            out.append(c)
    return "".join(out)


def table_lines():
    lines = []
    dict_ids = {}
    dicts = []
    for tid, table in enumerate(TABLES):
        for tag, entry in table.items():
            name, fmt = entry[0], entry[1]
            if fmt is None:
                tail = ["n"]
            elif callable(fmt):
                tail = ["f", FUNCS[fmt.__name__]]
            elif isinstance(fmt, tuple):
                tail = ["s", str(next(i for i, t in enumerate(TABLES) if t is fmt[1])), fmt[0]]
            else:
                if id(fmt) not in dict_ids:
                    dict_ids[id(fmt)] = len(dicts)
                    dicts.append(fmt)
                tail = ["d", str(dict_ids[id(fmt)])]
            lines.append("\t".join(["T", str(tid), str(tag), name] + tail))
    for did, d in enumerate(dicts):
        for k, v in d.items():
            assert isinstance(k, int) and isinstance(v, str)
            lines.append("\t".join(["D", str(did), str(k), v]))
    return lines


def text_fn(name, lines, chunk):
    out = ["fn %s() -> String {" % name, "    let mut s = String.new();"]
    buf = ""
    for ln in lines:
        buf += esc(ln + "\n")
        if len(buf) >= chunk:
            out.append('    s.push_str("%s");' % buf)
            buf = ""
    if buf:
        out.append('    s.push_str("%s");' % buf)
    out.append("    s")
    out.append("}")
    return "\n".join(out) + "\n"


def main():
    with open(os.path.join(HERE, "data", "jobs.tsv"), encoding="utf-8") as fh:
        jobs = [ln for ln in fh.read().split("\n") if ln]
    with open(SRC, encoding="utf-8") as fh:
        src = fh.read()
    if MARK in src:
        src = src[: src.index(MARK)]
    src = src.rstrip("\n") + "\n" + MARK
    src += text_fn("tables_text", table_lines(), 2000) + "\n"
    src += text_fn("jobs_text", jobs, 1)
    with open(SRC, "w", encoding="utf-8") as fh:
        fh.write(src)


main()
