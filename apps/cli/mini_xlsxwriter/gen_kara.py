"""Builds mini_xlsxwriter.kara: the port's pieces (p1.kara .. p6.kara) and,
after the MARK line, the generated functions, so the program reads no
file of its own:

- jobs_text() is data/jobs.txt;
- theme_text() the default theme part from the vendored theme.py,
  %-encoded;
- char_width_spec() utility.CHAR_WIDTHS, as "HH:N" pairs;
- formula_rule_spec() the re.sub() rules of Worksheet._prepare_formula(),
  in order, each marked as a future function or not;
- dynamic_function_spec() the names re_dynamic_function matches.

Run: python3 -I -B gen_kara.py"""
import ast
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
MARK = "\n// Generated by gen_kara.py from data/ and the vendored xlsxwriter.\n"
SRC = os.path.join(HERE, "mini_xlsxwriter.kara")
VENDOR = os.path.join(HERE, "vendor", "xlsxwriter")
PIECES = ["p1.kara", "p2.kara", "p3.kara", "p4.kara", "p5.kara", "p6.kara"]


def parse(name):
    with open(os.path.join(VENDOR, name)) as f:
        return ast.parse(f.read())


def pct(text):
    out = []
    for ch in text:
        if 32 <= ord(ch) < 127 and ch not in '"\\{}%~':
            out.append(ch)
        else:
            out.extend("%%%02X" % b for b in ch.encode("utf-8"))
    return "".join(out)


def theme():
    for node in ast.walk(parse("theme.py")):
        if isinstance(node, ast.Assign) and getattr(node.targets[0], "id", "") == "default_theme":
            return node.value.value
    raise SystemExit("no default_theme")


def char_widths():
    for node in parse("utility.py").body:
        if isinstance(node, ast.Assign) and getattr(node.targets[0], "id", "") == "CHAR_WIDTHS":
            d = ast.literal_eval(node.value)
            return " ".join("%X:%d" % (ord(k), v) for k, v in d.items())
    raise SystemExit("no CHAR_WIDTHS")


def rule(pattern, rep, future):
    if pattern.startswith("\\b"):
        kind, body = "b", pattern[2:]
    elif pattern.startswith("\\S"):
        kind, body = "S", pattern[2:]
    else:
        raise SystemExit("unexpected pattern %r" % pattern)
    assert body.endswith("\\("), pattern
    body = body[:-2] + "("
    assert re.fullmatch(r"[A-Z0-9_.(]+", body), pattern
    assert re.fullmatch(r"[A-Za-z0-9_.(]+", rep), rep
    return "%s %s %s %d" % (kind, body, rep, future)


def formula_rules():
    out = []
    for node in ast.walk(parse("worksheet.py")):
        if isinstance(node, ast.FunctionDef) and node.name == "_prepare_formula":
            future = 0
            for st in node.body:
                if isinstance(st, ast.If) and "use_future_functions" in ast.unparse(st.test):
                    future = 1
                    continue
                if isinstance(st, ast.Assign) and isinstance(st.value, ast.Call):
                    call = st.value
                    if ast.unparse(call.func) == "re.sub":
                        out.append(rule(call.args[0].value, call.args[1].value, future))
            return out
    raise SystemExit("no _prepare_formula")


def dynamic_names():
    for node in parse("worksheet.py").body:
        if isinstance(node, ast.Assign) and getattr(node.targets[0], "id", "") == "re_dynamic_function":
            text = node.value.args[0].value
            names = []
            for alt in text.split("|"):
                alt = alt.strip()
                assert alt.startswith("\\b") and alt.endswith("\\("), alt
                names.append(alt[2:-2] + "(")
            return " ".join(names)
    raise SystemExit("no re_dynamic_function")


def text_fn(name, lines, chunk=2000):
    out = ["fn %s() -> String {" % name, "    let mut s = String.new();"]
    buf = ""
    for ln in lines:
        assert all(32 <= ord(c) < 127 and c not in '"\\{}' for c in ln), ln
        buf += ln + "\\n"
        if len(buf) >= chunk:
            out.append('    s.push_str("%s");' % buf)
            buf = ""
    if buf:
        out.append('    s.push_str("%s");' % buf)
    out.append("    s")
    out.append("}")
    return "\n".join(out) + "\n"


def str_fn(name, text, chunk=2000):
    assert all(32 <= ord(c) < 127 and c not in '"\\{}' for c in text), name
    out = ["fn %s() -> String {" % name, "    let mut s = String.new();"]
    for i in range(0, len(text), chunk):
        out.append('    s.push_str("%s");' % text[i:i + chunk])
    out.append("    s")
    out.append("}")
    return "\n".join(out) + "\n"


def main():
    src = ""
    for p in PIECES:
        with open(os.path.join(HERE, p)) as f:
            src += f.read()
    with open(os.path.join(HERE, "data", "jobs.txt")) as f:
        jobs = f.read().splitlines()
    rules = formula_rules()
    gen = [text_fn("jobs_text", jobs), str_fn("theme_text", pct(theme())),
           str_fn("char_width_spec", char_widths()),
           text_fn("formula_rule_spec", rules),
           str_fn("dynamic_function_spec", dynamic_names())]
    with open(SRC, "w") as f:
        f.write(src + MARK + "\n" + "\n".join(gen))
    print("%d job lines, %d formula rules" % (len(jobs), len(rules)))


main()
