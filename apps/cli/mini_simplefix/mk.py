"""Write data/jobs.txt: the jobs mini_simplefix and oracle.py both play.

A job is a title line and steps. Values are written as
  b:<text>       bytes, ~XX for byte XX
  s:<text>       a str, ~XX for character XX
  i:<n>          an int
  -              None
Steps on messages (FixMessage):
  new <m>; pair <m> <tag> <value> [h]; str <m> <value>; strs <m> <value>...
  data <m> <len tag> <data tag> <value> [h]
  utc <m> <tag> <time> <precision> [h]     append_utc_timestamp; a time is
                                           D:YYYY-MM-DDTHH:MM:SS.ffffff or
                                           F:<seconds>.<6 digits> (a float)
  utct <m> <tag> <time> <precision>        append_utc_time_only
  atime <m> <tag> <time> <precision>       the deprecated append_time
  utcp <m> <tag> h m s ms us               append_utc_time_only_parts
  tzp <m> <tag> h m s ms us offset         append_tz_time_only_parts
  get <m> <tag> [nth]; rm <m> <tag> [nth]; has <m> <tag>; count <m>
  item <m> <i>; eq <m1> <m2>; enc <m> [raw]; show <m> [sep]
Steps on parsers (FixParser):
  parser <p> k=v ...    empty, missing, strip, stop_tag, stop_byte
  feed <p> <value>; next <p>; drain <p>; buf <p>; reset <p>
  addraw <p> <len> <data>; rmraw <p> <len> <data>
  set <p> stop_tag|stop_byte|empty|missing|strip <value>
  term <p> tag=<n>|char=<value>|both|none     set_message_terminator
  pipe <m> <p> <sizes>  encode m and feed it in chunks, reading after each
  pretty <value>        simplefix.pretty_print
Steps on the trading session (this app's own code):
  venue; logon <c>; order <c> <id> <side> <sym> <qty> <type> [price]
  cancel <c> <id> <orig>; bare <c> <type> <tag=value>...; tick <seconds>
  drop <from> <to> <n>; garble <from> <to>; cut <c>; heal <c>; logout <c>
  book <sym>; orders <c>; stats; log
Run: python3 -s -P -B mk.py"""
import os

out = []


def job(title):
    out.append("job " + title)


def step(*parts):
    out.append(" ".join(parts))


def esc(text):
    s = ""
    for c in text:
        if c == " " or c == "~" or ord(c) < 33 or ord(c) > 126:
            s += "~%02x" % ord(c)
        else:
            s += c
    return s


def b(text):
    return "b:" + esc(text)


def s(text):
    return "s:" + esc(text)


SOH = "\x01"


def wire(*fields):
    return b(SOH.join(fields) + SOH)


