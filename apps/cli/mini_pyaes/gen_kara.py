#!/usr/bin/env python3
"""Appends the generated functions to mini_pyaes.kara, after the MARK line,
so the kata reads only the files it writes itself.

- table_text(): the lookup tables of the vendored pyaes.AES class, one
  "<name> <hex> <hex> ..." line each (S, Si, T1 to T8, U1 to U4, rcon).
- jobs_text(): data/jobs.tsv verbatim.
- data_files(): the files under data/plain/ (as mk.py writes them), in hex;
  the port writes them out before it runs the jobs.

Run: python3 -I -B gen_kara.py"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "vendor"))
from pyaes.aes import AES  # noqa: E402

MARK = "\n// Generated by gen_kara.py from data/jobs.tsv.\n"
SRC = os.path.join(HERE, "mini_pyaes.kara")
TABLES = ["S", "Si", "T1", "T2", "T3", "T4", "T5", "T6", "T7", "T8",
          "U1", "U2", "U3", "U4", "rcon"]


def text_fn(name, lines, chunk=2000):
    out = ["fn %s() -> String {" % name, "    let mut s = String.new();"]
    buf = ""
    for ln in lines:
        assert all(32 <= ord(c) < 127 and c not in '"\\{}' for c in ln.replace("\t", " ")), ln
        buf += ln.replace("\t", "\\t") + "\\n"
        if len(buf) >= chunk:
            out.append('    s.push_str("%s");' % buf)
            buf = ""
    if buf:
        out.append('    s.push_str("%s");' % buf)
    out.append("    s")
    out.append("}")
    return "\n".join(out) + "\n"


def main():
    parts = []
    lines = []
    for t in TABLES:
        lines.append(t + " " + " ".join("%x" % v for v in getattr(AES, t)))
    parts.append(text_fn("table_text", lines))
    with open(os.path.join(HERE, "data", "jobs.tsv")) as f:
        jobs = f.read().split("\n")
    parts.append(text_fn("jobs_text", [j for j in jobs if j]))
    plain = os.path.join(HERE, "data", "plain")
    files = []
    for name in sorted(os.listdir(plain)):
        with open(os.path.join(plain, name), "rb") as f:
            files.append("%s %s" % (name, f.read().hex() or "-"))
    parts.append(text_fn("plain_files_text", files))
    with open(SRC) as f:
        src = f.read()
    if MARK in src:
        src = src[:src.index(MARK)]
    with open(SRC, "w") as f:
        f.write(src + MARK + "\n" + "\n".join(parts))


main()
