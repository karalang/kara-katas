#!/usr/bin/env python3
r"""Appends two generated functions to mini_intelhex.kara, so the kata reads
no files at run time:

  usage_text()  hexmerge.py's USAGE string, read with Python's ast module
  jobs_text()   data/jobs.tsv, verbatim (it carries every image as hex)

Run after mk.py; idempotent. Run: python3 -I -B gen_kara.py"""
import ast

MARK = "\n// Generated by gen_kara.py from vendor/scripts/hexmerge.py and data/jobs.tsv.\n"


def esc(s):
    out = []
    for c in s:
        if c == "\\":
            out.append("\\\\")
        elif c == '"':
            out.append('\\"')
        elif c == "{" or c == "}":
            out.append(c)
        elif c == "\t":
            out.append("\\t")
        elif ord(c) < 0x20:
            out.append("\\x%02x" % ord(c))
        else:
            out.append(c)
    return "".join(out)


def text_fn(name, text, final_newline):
    lines = text.split("\n")
    body = ["fn %s() -> String {\n" % name, "    let mut s = String.new();\n"]
    for i, ln in enumerate(lines):
        last = i == len(lines) - 1
        if last and ln == "":
            break
        nl = "" if last and not final_newline else "\\n"
        body.append('    s.push_str("%s%s");\n' % (esc(ln), nl))
    body.append("    s\n}\n")
    return body


def usage():
    tree = ast.parse(open("vendor/scripts/hexmerge.py", encoding="utf-8").read())
    for node in tree.body:
        if isinstance(node, ast.Assign) and node.targets[0].id == "USAGE":
            return ast.literal_eval(node.value)
    raise SystemExit("no USAGE")


with open("data/jobs.tsv", encoding="utf-8") as fh:
    jobs = fh.read()

with open("mini_intelhex.kara", encoding="utf-8") as fh:
    src = fh.read()
cut = src.find(MARK)
if cut != -1:
    src = src[:cut]
src = src.rstrip("\n") + "\n"

u = usage()
out = [MARK, "\n// USAGE from hexmerge.py, verbatim.\n"] + text_fn("usage_text", u, u.endswith("\n")) + \
    ["\n// data/jobs.tsv, as mk.py writes it.\n"] + text_fn("jobs_text", jobs, True)
with open("mini_intelhex.kara", "w", encoding="utf-8") as fh:
    fh.write(src + "".join(out))
