# Prints the data section at the end of mini_tinycss2.kara: the files the
# run writes into data/ (the suites and the stylesheets, as mk.py lays
# them out), the color keywords of tinycss2.color3 and color4, the labels
# of webencodings, and the 128 upper characters of each single-byte
# encoding those labels name (from Python's codecs, as webencodings
# uses them).
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "data")
sys.path.insert(0, HERE)

import webencodings  # noqa: E402
from webencodings.labels import LABELS  # noqa: E402
from tinycss2 import color3, color4  # noqa: E402


def lit(s):
    out = []
    for c in s:
        o = ord(c)
        if c == "\\":
            out.append("\\\\")
        elif c == '"':
            out.append('\\"')
        elif o < 32 or o == 127 or 0xD800 <= o < 0xE000 or not c.isprintable():
            out.append(f"\\u{{{o:x}}}")
        else:
            out.append(c)
    return '"' + "".join(out) + '"'


def chunked(name, text, per=200):
    pieces = [text[i:i + 400] for i in range(0, len(text), 400)] or [""]
    groups = [pieces[i:i + per] for i in range(0, len(pieces), per)]
    out = []
    for gi, g in enumerate(groups):
        out.append(f"fn {name}_{gi}(out: mut ref String) {{")
        for p in g:
            out.append(f"    out.push_str({lit(p)});")
        out.append("}")
        out.append("")
    out.append(f"fn {name}() -> String {{")
    out.append("    let mut out = String.new();")
    for gi in range(len(groups)):
        out.append(f"    {name}_{gi}(mut out);")
    out.append("    out")
    out.append("}")
    out.append("")
    return "\n".join(out)


def data_files():
    files = []
    for root, _, names in os.walk(DATA):
        for n in names:
            path = os.path.join(root, n)
            files.append(os.path.relpath(path, DATA))
    files.sort()
    out = []
    for rel in files:
        raw = open(os.path.join(DATA, rel), "rb").read()
        try:
            out.append((rel, raw.decode("utf-8"), False))
        except UnicodeDecodeError:
            out.append((rel, raw.hex(), True))
    return out


def single_byte():
    out = []
    for name in sorted(set(LABELS.values())):
        if name in ("utf-8", "utf-16be", "utf-16le"):
            continue
        codec = webencodings.lookup(name).codec_info
        try:
            whole = codec.decode(bytes(range(256)), "replace")[0]
        except Exception:
            continue
        each = [codec.decode(bytes([b]), "replace")[0] for b in range(256)]
        if len(whole) != 256 or any(len(c) != 1 for c in each) or "".join(each) != whole:
            continue  # a multi-byte encoding: the port has no codec for it
        if whole[:128] != "".join(map(chr, range(128))):
            continue  # not ASCII-compatible (hz-gb-2312 is a shifting encoding)
        out.append((name, whole[128:]))
    return out


def main():
    print("// ---------------------------------------------------------------- data")
    print("// Generated by gen_kara.py.")
    print()
    files = data_files()
    for i, (_, text, _) in enumerate(files):
        print(chunked(f"file_{i}", text))
    print("// (path under data/, contents, whether the contents are hex)")
    print("fn data_files() -> Vec[(String, String, bool)] {")
    print("    let mut v: Vec[(String, String, bool)] = Vec.new();")
    for i, (rel, _, hexed) in enumerate(files):
        print(f"    v.push(({lit(rel)}.to_string(), file_{i}(), {'true' if hexed else 'false'}));")
    print("    v")
    print("}")
    print()
    level3 = dict(color3._BASIC_COLOR_KEYWORDS + color3._EXTENDED_COLOR_KEYWORDS)
    print("// (keyword, r, g, b, only in Level 4)")
    print("fn color_keywords() -> Vec[(Str, i64, i64, i64, bool)] {")
    print("    vec![")
    for k, (r, g, b) in color4._COLOR_KEYWORDS.items():
        print(f"        ({lit(k)}, {r}, {g}, {b}, {'false' if k in level3 else 'true'}),")
    print("    ]")
    print("}")
    print()
    print("// webencodings.labels.LABELS")
    print("fn encoding_labels() -> Vec[(Str, Str)] {")
    print("    vec![")
    for k, v in LABELS.items():
        print(f"        ({lit(k)}, {lit(v)}),")
    print("    ]")
    print("}")
    print()
    print("// (name, the characters of bytes 0x80 to 0xFF)")
    print("fn single_byte_codecs() -> Vec[(Str, Str)] {")
    print("    vec![")
    for name, high in single_byte():
        print(f"        ({lit(name)}, {lit(high)}),")
    print("    ]")
    print("}")


main()
