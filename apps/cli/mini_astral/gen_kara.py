#!/usr/bin/env python3
r"""Appends three generated functions to mini_astral.kara, so the kata reads
no files at run time:

  table4()        the moon's series terms (table4_v, table4_u, table4_w in
                  vendor/astral/table4.py), read with Python's ast module
  location_info() the geocoder's built-in location list (_LOCATION_INFO in
                  vendor/astral/geocoder.py), verbatim
  jobs_text()     data/jobs.tsv, verbatim

Run after mk.py; idempotent. Run: python3 -I -B gen_kara.py"""
import ast

MARK = "\n// Generated by gen_kara.py from vendor/astral and data/jobs.tsv.\n"
ARGS = ["Gm", "Fm", "D", "Om", "Ls", "Gs", "L2"]


def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\t", "\\t")


def text_fn(name, text):
    lines = text.split("\n")
    if lines and lines[-1] == "":
        lines.pop()
    body = ["fn %s() -> String {\n" % name, "    let mut s = String.new();\n"]
    for ln in lines:
        body.append('    s.push_str("%s\\n");\n' % esc(ln))
    body.append("    s\n}\n")
    return body


def table4_fn():
    tree = ast.parse(open("vendor/astral/table4.py", encoding="utf-8").read())
    tables = {}
    for node in tree.body:
        if isinstance(node, ast.AnnAssign) and node.target.id.startswith("table4_"):
            tables[node.target.id] = node.value.elts
    body = ["\n// The series terms of table4.py; `which` is 0 for v, 1 for u, 2 for w.\n",
            "fn table4(which: i64) -> Vec[T4Row] {\n",
            "    let mut t: Vec[T4Row] = Vec.new();\n"]
    for i, name in enumerate(["table4_v", "table4_u", "table4_w"]):
        body.append("    if which == %d {\n" % i)
        for row in tables[name]:
            coef = ast.literal_eval(row.args[0])
            tflag = ast.literal_eval(row.args[1])
            fn = row.args[2].id
            keys = [k.id for k in row.args[3].keys]
            assert keys == ARGS, keys
            mults = [ast.literal_eval(v) for v in row.args[3].values]
            body.append("        t.push(T4Row { coefficient: %r, t: %s, is_sin: %s, m: [%s] });\n"
                        % (float(coef), "true" if tflag else "false",
                           "true" if fn == "sin" else "false", ", ".join(str(m) for m in mults)))
        body.append("    }\n")
    body.append("    t\n}\n")
    return body


def location_text():
    tree = ast.parse(open("vendor/astral/geocoder.py", encoding="utf-8").read())
    for node in tree.body:
        if isinstance(node, ast.Assign) and node.targets[0].id == "_LOCATION_INFO":
            return ast.literal_eval(node.value)
    raise SystemExit("no _LOCATION_INFO")


with open("data/jobs.tsv", encoding="utf-8") as fh:
    jobs = fh.read()

with open("mini_astral.kara", encoding="utf-8") as fh:
    src = fh.read()
cut = src.find(MARK)
if cut != -1:
    src = src[:cut]
src = src.rstrip("\n") + "\n"

out = [MARK] + table4_fn() + ["\n// _LOCATION_INFO from geocoder.py, verbatim.\n"] + \
    text_fn("location_info", location_text()) + ["\n// data/jobs.tsv, as mk.py writes it.\n"] + \
    text_fn("jobs_text", jobs)
with open("mini_astral.kara", "w", encoding="utf-8") as fh:
    fh.write(src + "".join(out))
