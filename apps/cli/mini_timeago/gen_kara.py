#!/usr/bin/env python3
"""Appends the generated functions to mini_timeago.kara, after the MARK
line, so the kata reads no files at run time: jobs_text() is data/jobs.tsv
verbatim; locale_text() holds the vendored locale tables, an "L<TAB>name
<TAB>list|func" line for each locale followed by one "R" line per row of
its LOCALE list (or, for the six locales whose LOCALE is a function, of the
`base` table that function reads); and digits_text() lists the runs of
decimal digits that int() reads, "lo hi" in hex, each counting up from 0
at lo.

Run: python3 -I -B gen_kara.py"""
import ast
import os
import unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))
MARK = "\n// Generated by gen_kara.py from data/jobs.tsv.\n"
SRC = os.path.join(HERE, "mini_timeago.kara")
LOCDIR = os.path.join(HERE, "vendor", "timeago", "locales")
SKIP = {"__init__", "create_tests", "import_locale"}


def esc(s):
    out = []
    for c in s:
        if c == "\\":
            out.append("\\\\")
        elif c == '"':
            out.append('\\"')
        elif c == "\t":
            out.append("\\t")
        elif c == "\n":
            out.append("\\n")
        elif ord(c) < 32 or ord(c) == 127:
            out.append("\\x%02x" % ord(c))
        else:
            out.append(c)
    return "".join(out)


def text_fn(name, lines, chunk):
    out = ["fn %s() -> String {" % name, "    let mut s = String.new();"]
    buf = ""
    for ln in lines:
        buf += esc(ln + "\n")
        if len(buf) >= chunk:
            out.append('    s.push_str("%s");' % buf)
            buf = ""
    if buf:
        out.append('    s.push_str("%s");' % buf)
    out.append("    s")
    out.append("}")
    return "\n".join(out) + "\n"


def locale_lines():
    """Reads each locale's table with ast.literal_eval, without importing
    the module."""
    out = []
    for fn in sorted(os.listdir(LOCDIR)):
        name, ext = os.path.splitext(fn)
        if ext != ".py" or name in SKIP:
            continue
        with open(os.path.join(LOCDIR, fn), encoding="utf-8") as fh:
            tree = ast.parse(fh.read())
        found = {}
        for node in tree.body:
            if isinstance(node, ast.Assign) and len(node.targets) == 1:
                t = node.targets[0]
                if isinstance(t, ast.Name):
                    found[t.id] = node.value
        loc = found["LOCALE"]
        if isinstance(loc, ast.Name):
            assert loc.id == "generate", name
            rows, kind = ast.literal_eval(found["base"]), "func"
        else:
            rows, kind = ast.literal_eval(loc), "list"
        assert len(rows) == 14, name
        out.append("L\t%s\t%s" % (name, kind))
        for r in rows:
            for t in r:
                assert "\t" not in t and "\n" not in t, (name, t)
            out.append("R\t" + "\t".join(r))
    return out


def digit_lines():
    out = []
    for cp in range(0x80, 0x110000):
        if unicodedata.decimal(chr(cp), None) == 0:
            hi = cp
            while unicodedata.decimal(chr(hi + 1), None) == hi + 1 - cp:
                hi += 1
            out.append("%x %x" % (cp, hi))
    return out


def main():
    with open(os.path.join(HERE, "data", "jobs.tsv"), encoding="utf-8") as fh:
        jobs = [ln for ln in fh.read().split("\n") if ln]
    with open(SRC, encoding="utf-8") as fh:
        src = fh.read()
    if MARK in src:
        src = src[: src.index(MARK)]
    src = src.rstrip("\n") + "\n" + MARK
    src += text_fn("jobs_text", jobs, 1)
    src += "\n" + text_fn("locale_text", locale_lines(), 1000)
    src += "\n" + text_fn("digits_text", digit_lines(), 1000)
    with open(SRC, "w", encoding="utf-8") as fh:
        fh.write(src)


main()
