#!/usr/bin/env python3
"""Appends the generated functions to mini_holidays.kara, after the MARK
line, so the kata reads only the files it writes itself: jobs_text() is
data/jobs.tsv, one hex line a step; inputs_text() the files mk.py writes
(data/files.txt lists them), one "<path> <hex>" a line; and static_text()
the special-holiday tables of the vendored library's *StaticHolidays
classes, one hex line "<entity>|<table>|<year>|<month>|<day>|<name>" an
entry, in the order the tables list them.

Run: python3 -I -B gen_kara.py"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
MARK = "\n// Generated by gen_kara.py from data/jobs.tsv.\n"
SRC = os.path.join(HERE, "mini_holidays.kara")
sys.path.insert(0, os.path.join(HERE, "vendor"))

from holidays.countries.germany import GermanyStaticHolidays  # noqa: E402
from holidays.countries.united_kingdom import UnitedKingdomStaticHolidays  # noqa: E402
from holidays.financial.european_central_bank import (  # noqa: E402
    EuropeanCentralBankStaticHolidays,
)
from holidays.financial.ny_stock_exchange import NewYorkStockExchangeStaticHolidays  # noqa: E402

STATIC = [
    ("GB", UnitedKingdomStaticHolidays),
    ("DE", GermanyStaticHolidays),
    ("NYSE", NewYorkStockExchangeStaticHolidays),
    ("ECB", EuropeanCentralBankStaticHolidays),
]


def text_fn(name, lines, chunk=2000):
    out = ["fn %s() -> String {" % name, "    let mut s = String.new();"]
    buf = ""
    for ln in lines:
        assert all(32 <= ord(c) < 127 and c not in '"\\{}' for c in ln), ln
        buf += ln + "\\n"
        if len(buf) >= chunk:
            out.append('    s.push_str("%s");' % buf)
            buf = ""
    if buf:
        out.append('    s.push_str("%s");' % buf)
    out.append("    s")
    out.append("}")
    return "\n".join(out) + "\n"


def static_lines():
    lines = []
    for entity, cls in STATIC:
        for attr, table in cls.__dict__.items():
            if not attr.startswith("special_"):
                continue
            for year, data in table.items():
                rows = data if isinstance(data[0], tuple) else (data,)
                for month, day, name in rows:
                    row = "%s|%s|%d|%d|%d|%s" % (entity, attr, year, month, day, name)
                    lines.append(row.encode("utf-8").hex())
    return lines


def main():
    with open(os.path.join(HERE, "data", "jobs.tsv"), "rb") as f:
        jobs = f.read().split(b"\n")
    parts = [text_fn("jobs_text", [j.hex() for j in jobs if j])]
    files = []
    with open(os.path.join(HERE, "data", "files.txt")) as f:
        inputs = [ln for ln in f.read().split("\n") if ln]
    for name in inputs:
        with open(os.path.join(HERE, "data", name), "rb") as f:
            files.append("%s %s" % (name, f.read().hex()))
    parts.append(text_fn("inputs_text", files))
    parts.append(text_fn("static_text", static_lines()))
    with open(SRC) as f:
        src = f.read()
    if MARK in src:
        src = src[: src.index(MARK)]
    with open(SRC, "w") as f:
        f.write(src + MARK + "\n" + "\n".join(parts))


main()
