# Prints the data section at the end of mini_hpack.kara: the files the
# run writes into data/ (as mk.py lays them out), hpack's static table,
# the Huffman codes of RFC 7541 Appendix B and hpack's Huffman decoding
# state machine (huffman_table.HUFFMAN_TABLE, as a hex string of
# state, flags and symbol bytes).
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "data")
sys.path.insert(0, HERE)

from hpack.huffman_constants import REQUEST_CODES, REQUEST_CODES_LENGTH  # noqa: E402
from hpack.huffman_table import HUFFMAN_TABLE  # noqa: E402
from hpack.table import HeaderTable  # noqa: E402


def lit(s):
    out = []
    for c in s:
        o = ord(c)
        if c == "\\":
            out.append("\\\\")
        elif c == '"':
            out.append('\\"')
        elif o < 32 or o == 127 or not c.isprintable():
            out.append(f"\\u{{{o:x}}}")
        else:
            out.append(c)
    return '"' + "".join(out) + '"'


def chunked(name, text, per=200):
    pieces = [text[i:i + 400] for i in range(0, len(text), 400)] or [""]
    groups = [pieces[i:i + per] for i in range(0, len(pieces), per)]
    out = []
    for gi, g in enumerate(groups):
        out.append(f"fn {name}_{gi}(out: mut ref String) {{")
        for p in g:
            out.append(f"    out.push_str({lit(p)});")
        out.append("}")
        out.append("")
    out.append(f"fn {name}() -> String {{")
    out.append("    let mut out = String.new();")
    for gi in range(len(groups)):
        out.append(f"    {name}_{gi}(mut out);")
    out.append("    out")
    out.append("}")
    out.append("")
    return "\n".join(out)


def main():
    print("// ---------------------------------------------------------------- data")
    print("// Generated by gen_kara.py.")
    print()
    files = sorted(os.listdir(DATA))
    for i, rel in enumerate(files):
        with open(os.path.join(DATA, rel), encoding="utf-8") as f:
            print(chunked(f"file_{i}", f.read()))
    print("// (path under data/, contents)")
    print("fn data_files() -> Vec[(String, String)] {")
    print("    let mut v: Vec[(String, String)] = Vec.new();")
    for i, rel in enumerate(files):
        print(f"    v.push(({lit(rel)}.to_string(), file_{i}()));")
    print("    v")
    print("}")
    print()
    print("// HeaderTable.STATIC_TABLE")
    print("fn static_table() -> Vec[(Str, Str)] {")
    print("    vec![")
    for n, v in HeaderTable.STATIC_TABLE:
        print(f"        ({lit(n.decode())}, {lit(v.decode())}),")
    print("    ]")
    print("}")
    print()
    print("// REQUEST_CODES and REQUEST_CODES_LENGTH, one (code, length) per symbol")
    print("fn huffman_codes() -> Vec[(i64, i64)] {")
    print("    vec![")
    for c, n in zip(REQUEST_CODES, REQUEST_CODES_LENGTH):
        print(f"        ({c:#x}, {n}),")
    print("    ]")
    print("}")
    print()
    text = "".join(f"{s:02x}{f:02x}{b:02x}" for s, f, b in HUFFMAN_TABLE)
    print("// HUFFMAN_TABLE: 256 nodes of 16 (state, flags, symbol) entries")
    print(chunked("huffman_fsm_hex", text))


main()
