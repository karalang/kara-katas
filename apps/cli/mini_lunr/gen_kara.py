"""Builds mini_lunr.kara: the port (mini_lunr.kara up to the MARK line)
and, after it, the generated functions, so the program reads no file of
its own: docs_text() is data/docs.txt, queries_text() data/queries.txt
(with % and backslash %-encoded), and stop_word_spec() the vendored
lunr's English stop words, in its order.

Run: python3 -I -B gen_kara.py"""
import ast
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "mini_lunr.kara")
MARK = "\n// Generated by gen_kara.py from data/ and the vendored lunr.\n"


def str_fn(name, text, chunk=2000):
    assert all(32 <= ord(c) < 127 and c not in '"\\{}' or c == "\n" for c in text), name
    text = text.replace("\n", "\\n")
    out = ["fn %s() -> String {" % name, "    let mut s = String.new();"]
    i = 0
    while i < len(text):
        j = min(i + chunk, len(text))
        if text[j - 1:j] == "\\":
            j += 1
        out.append('    s.push_str("%s");' % text[i:j])
        i = j
    out += ["    s", "}"]
    return "\n".join(out) + "\n"


def stop_words():
    with open(os.path.join(HERE, "vendor", "lunr", "stop_word_filter.py")) as f:
        tree = ast.parse(f.read())
    for node in tree.body:
        if isinstance(node, ast.Assign) and getattr(node.targets[0], "id", "") == "WORDS":
            return " ".join(e.value for e in node.value.elts)
    raise SystemExit("no WORDS")


def main():
    with open(SRC) as f:
        src = f.read()
    if MARK in src:
        src = src[:src.index(MARK)]
    with open(os.path.join(HERE, "data", "docs.txt")) as f:
        docs = f.read()
    with open(os.path.join(HERE, "data", "queries.txt")) as f:
        queries = f.read().replace("%", "%25").replace("\\", "%5C")
    gen = [str_fn("docs_text", docs), str_fn("queries_text", queries), str_fn("stop_word_spec", stop_words())]
    with open(SRC, "w") as f:
        f.write(src + MARK + "\n" + "\n".join(gen))
    print("%d pages, %d queries" % (docs.count("\n"), queries.count("\n")))


main()
