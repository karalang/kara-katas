#!/usr/bin/env python3
"""Appends inputs_text() to mini_arrow.kara, after the MARK line, so the
program reads only the files it writes itself. inputs_text() holds every
file under data/, one "<path> <hex>" a line: the files mk.py writes and
data/locales.txt, which this script extracts from the vendored
arrow/locales.py first.

data/locales.txt has one block a locale class the port supports, with the
attributes it inherits resolved, one tab-separated line an attribute.

Run: python3 -I -B gen_kara.py"""
import ast
import os

HERE = os.path.dirname(os.path.abspath(__file__))
MARK = "\n// Generated by gen_kara.py from data/.\n"
SRC = os.path.join(HERE, "mini_arrow.kara")

CLASSES = ["EnglishLocale", "ItalianLocale", "SpanishLocale", "FrenchLocale",
           "FrenchCanadianLocale", "JapaneseLocale", "FinnishLocale", "ChineseCNLocale",
           "KoreanLocale", "DutchLocale", "PolishLocale", "RussianLocale", "GermanLocale",
           "AustrianLocale", "PortugueseLocale", "BrazilianPortugueseLocale", "CzechLocale"]
LISTS = ["month_names", "month_abbreviations", "day_names", "day_abbreviations"]


def read_classes(path):
    with open(path, encoding="utf-8") as f:
        tree = ast.parse(f.read())
    classes = {}
    for node in tree.body:
        if not isinstance(node, ast.ClassDef):
            continue
        attrs = {}
        for st in node.body:
            if isinstance(st, ast.Assign) and len(st.targets) == 1:
                t, v = st.targets[0], st.value
                if isinstance(t, ast.Name):
                    if (isinstance(v, ast.Call) and isinstance(v.func, ast.Attribute)
                            and v.func.attr == "copy" and isinstance(v.func.value, ast.Name)):
                        attrs[t.id] = dict(attrs[v.func.value.id])
                    else:
                        try:
                            attrs[t.id] = ast.literal_eval(v)
                        except ValueError:
                            pass
                elif isinstance(t, ast.Subscript) and isinstance(t.value, ast.Name):
                    attrs[t.value.id][ast.literal_eval(t.slice)] = ast.literal_eval(v)
            elif isinstance(st, ast.AnnAssign) and st.value is not None and isinstance(st.target, ast.Name):
                try:
                    attrs[st.target.id] = ast.literal_eval(st.value)
                except ValueError:
                    pass
        bases = [b.id for b in node.bases if isinstance(b, ast.Name)]
        classes[node.name] = (bases, attrs)
    return classes


def lookup(classes, cls, name):
    bases, attrs = classes[cls]
    if name in attrs:
        return True, attrs[name]
    for b in bases:
        if b in classes:
            found, v = lookup(classes, b, name)
            if found:
                return True, v
    return False, None


def clean(s):
    assert isinstance(s, str) and "\t" not in s and "\n" not in s, s
    return s


def locale_lines(classes):
    out = []
    for cls in CLASSES:
        def get(name):
            return lookup(classes, cls, name)[1]
        out.append("locale\t" + cls)
        out.append("\t".join(["names"] + [clean(n) for n in get("names")]))
        out.append("past\t" + clean(get("past")))
        out.append("future\t" + clean(get("future")))
        if get("and_word") is not None:
            out.append("and\t" + clean(get("and_word")))
        for key, form in get("timeframes").items():
            if isinstance(form, str):
                out.append("tf\t%s\t%s" % (key, clean(form)))
            else:
                for sub, text in form.items():
                    out.append("tfm\t%s\t%s\t%s" % (key, sub, clean(text)))
        found, dist = lookup(classes, cls, "timeframes_only_distance")
        if found:
            for key, form in dist.items():
                out.append("tfd\t%s\t%s" % (key, clean(form)))
        for key, v in get("meridians").items():
            out.append("mer\t%s\t%s" % (key, clean(v)))
        for name in LISTS:
            out.append("\t".join([name] + [clean(x) for x in get(name)]))
        out.append("ordinal_day_re\t" + clean(get("ordinal_day_re")))
        for name in ["special_dayframes", "special_yearframes"]:
            found, frames = lookup(classes, cls, name)
            if found:
                for k, v in frames.items():
                    out.append("%s\t%d\t%s" % (name, k, clean(v)))
    return out


def text_fn(name, lines, chunk=2000):
    out = ["fn %s() -> String {" % name, "    let mut s = String.new();"]
    buf = ""
    for ln in lines:
        assert all(32 <= ord(c) < 127 and c not in '"\\{}' for c in ln), ln
        buf += ln + "\\n"
        if len(buf) >= chunk:
            out.append('    s.push_str("%s");' % buf)
            buf = ""
    if buf:
        out.append('    s.push_str("%s");' % buf)
    out.append("    s")
    out.append("}")
    return "\n".join(out) + "\n"


def rle_hex(b):
    out = []
    i = 0
    while i < len(b):
        j = i
        while j < len(b) and b[j] == 0:
            j += 1
        if j - i >= 8:
            out.append("z%d." % (j - i))
            i = j
        else:
            out.append("%02x" % b[i])
            i += 1
    return "".join(out)


def main():
    classes = read_classes(os.path.join(HERE, "vendor", "arrow", "locales.py"))
    with open(os.path.join(HERE, "data", "locales.txt"), "w", encoding="utf-8") as f:
        f.write("\n".join(locale_lines(classes)) + "\n")
    files = []
    for root, dirs, names in os.walk(os.path.join(HERE, "data")):
        dirs.sort()
        for name in sorted(names):
            path = os.path.join(root, name)
            rel = os.path.relpath(path, HERE).replace(os.sep, "/")
            with open(path, "rb") as f:
                files.append("%s %s" % (rel, rle_hex(f.read())))
    with open(SRC) as f:
        src = f.read()
    if MARK in src:
        src = src[:src.index(MARK)]
    with open(SRC, "w") as f:
        f.write(src + MARK + "\n" + text_fn("inputs_text", files))


main()
