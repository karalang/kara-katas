# Prints the data section at the end of mini_qrcode.kara: the files the
# run writes into data/ (subdirectories included), as mk.py lays them
# out (read without newline translation, so a file with CRLF line ends
# keeps them).
import os

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "data")

def lit(s):
    out = []
    for c in s:
        o = ord(c)
        if c == "\\":
            out.append("\\\\")
        elif c == '"':
            out.append('\\"')
        elif o < 32 or o == 127 or not c.isprintable():
            out.append(f"\\u{{{o:x}}}")
        else:
            out.append(c)
    return '"' + "".join(out) + '"'


def chunked(name, text, per=200):
    pieces = [text[i:i + 400] for i in range(0, len(text), 400)] or [""]
    groups = [pieces[i:i + per] for i in range(0, len(pieces), per)]
    out = []
    for gi, g in enumerate(groups):
        out.append(f"fn {name}_{gi}(out: mut ref String) {{")
        for p in g:
            out.append(f"    out.push_str({lit(p)});")
        out.append("}")
        out.append("")
    out.append(f"fn {name}() -> String {{")
    out.append("    let mut out = String.new();")
    for gi in range(len(groups)):
        out.append(f"    {name}_{gi}(mut out);")
    out.append("    out")
    out.append("}")
    out.append("")
    return "\n".join(out)


def main():
    print("// ---------------------------------------------------------------- data")
    print("// Generated by gen_kara.py.")
    print()
    files = sorted(os.path.relpath(os.path.join(d, f), DATA).replace(os.sep, "/")
                   for d, _, fs in os.walk(DATA) for f in fs)
    for i, rel in enumerate(files):
        with open(os.path.join(DATA, rel), encoding="utf-8", newline="") as f:
            print(chunked(f"file_{i}", f.read()))
    print("// (path under data/, contents)")
    print("fn data_files() -> Vec[(String, String)] {")
    print("    let mut v: Vec[(String, String)] = Vec.new();")
    for i, rel in enumerate(files):
        print(f"    v.push(({lit(rel)}.to_string(), file_{i}()));")
    print("    v")
    print("}")


main()
