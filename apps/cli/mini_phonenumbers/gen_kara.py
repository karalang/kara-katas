#!/usr/bin/env python3
"""Appends inputs_text() to mini_phonenumbers.kara, after the MARK line,
so the program reads only the files it writes itself. inputs_text() holds
every file under data/, one "<path> <hex>" a line: the files mk.py writes
and two this script extracts from the vendored metadata first.

- data/codes.txt: the calling code table of data/__init__.py, one
  "<code> <region> <region> ..." a line, in the table's order;
- data/metadata.jsonl: one JSON object a vendored region_*.py file, its
  PhoneMetadata(...) call read with ast: the scalar fields under their own
  names, each PhoneNumberDesc as {"p", "ex", "pl", "plo"} and each
  NumberFormat as {"p", "f", "ld", "npr", "npo", "dcr"}. A field the call
  leaves out is left out here too.

Every template (formats, prefix rules, transform rules) must hold no
backslash but \\1 to \\9 not followed by a digit, the only form the port's
re.sub expands; the script checks.

Run: python3 -I -B gen_kara.py"""
import ast
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
MARK = "\n// Generated by gen_kara.py from data/.\n"
SRC = os.path.join(HERE, "mini_phonenumbers.kara")
META = os.path.join(HERE, "vendor", "phonenumbers", "data")
TEMPLATE = re.compile(r"(?:[^\\]|\\[1-9](?![0-9]))*\Z")

DESCS = ["general_desc", "fixed_line", "mobile", "toll_free", "premium_rate", "shared_cost",
         "personal_number", "voip", "pager", "uan", "voicemail", "no_international_dialling"]
SCALARS = ["id", "country_code", "international_prefix", "preferred_international_prefix",
           "national_prefix", "preferred_extn_prefix", "national_prefix_for_parsing",
           "national_prefix_transform_rule", "main_country_for_code", "leading_digits",
           "mobile_number_portable_region"]


def template(s):
    assert TEMPLATE.match(s), s
    return s


def kwargs(call, name):
    assert isinstance(call, ast.Call) and call.func.id == name, ast.dump(call)
    assert not call.args
    return {k.arg: k.value for k in call.keywords}


def desc(call):
    kw = kwargs(call, "PhoneNumberDesc")
    out = {}
    for key, short in [("national_number_pattern", "p"), ("example_number", "ex"),
                       ("possible_length", "pl"), ("possible_length_local_only", "plo")]:
        if key in kw:
            v = ast.literal_eval(kw[key])
            out[short] = list(v) if isinstance(v, tuple) else v
    assert set(kw) <= {"national_number_pattern", "example_number", "possible_length",
                       "possible_length_local_only"}, kw.keys()
    return out


def number_format(call):
    kw = kwargs(call, "NumberFormat")
    out = {}
    for key, short in [("pattern", "p"), ("format", "f"), ("leading_digits_pattern", "ld"),
                       ("national_prefix_formatting_rule", "npr"),
                       ("national_prefix_optional_when_formatting", "npo"),
                       ("domestic_carrier_code_formatting_rule", "dcr")]:
        if key in kw:
            out[short] = ast.literal_eval(kw[key])
    for key in ["f", "npr", "dcr"]:
        if key in out:
            template(out[key])
    assert set(kw) <= {"pattern", "format", "leading_digits_pattern",
                       "national_prefix_formatting_rule",
                       "national_prefix_optional_when_formatting",
                       "domestic_carrier_code_formatting_rule"}, kw.keys()
    return out


def region(path):
    with open(path, encoding="utf-8") as f:
        tree = ast.parse(f.read())
    assign = tree.body[-1]
    kw = kwargs(assign.value, "PhoneMetadata")
    out = {}
    for key, v in kw.items():
        if key in DESCS:
            out[key] = desc(v)
        elif key in ("number_format", "intl_number_format"):
            assert isinstance(v, ast.List)
            out[key] = [number_format(e) for e in v.elts]
        elif key in SCALARS:
            out[key] = ast.literal_eval(v)
        else:
            raise AssertionError("field %s in %s" % (key, path))
    if "national_prefix_transform_rule" in out:
        template(out["national_prefix_transform_rule"])
    return out


def codes():
    with open(os.path.join(META, "__init__.py"), encoding="utf-8") as f:
        for node in ast.parse(f.read()).body:
            if (isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name)
                    and node.targets[0].id == "_COUNTRY_CODE_TO_REGION_CODE"):
                table = ast.literal_eval(node.value)
    return ["%d %s" % (cc, " ".join(rs)) for cc, rs in table.items()]


def text_fn(name, lines, chunk=2000):
    out = ["fn %s() -> String {" % name, "    let mut s = String.new();"]
    buf = ""
    for ln in lines:
        piece = ln + "\n"
        if len(buf) + len(piece) > chunk and buf:
            out.append("    s.push_str(%s);" % json.dumps(buf))
            buf = ""
        buf += piece
    if buf:
        out.append("    s.push_str(%s);" % json.dumps(buf))
    out.append("    s")
    out.append("}")
    return "\n".join(out) + "\n"


def main():
    names = sorted(n for n in os.listdir(META) if n.startswith("region_") and n.endswith(".py"))
    with open(os.path.join(HERE, "data", "metadata.jsonl"), "w", encoding="utf-8") as f:
        for n in names:
            f.write(json.dumps(region(os.path.join(META, n)), ensure_ascii=False) + "\n")
    with open(os.path.join(HERE, "data", "codes.txt"), "w", encoding="utf-8") as f:
        f.write("\n".join(codes()) + "\n")
    files = []
    for root, dirs, fnames in os.walk(os.path.join(HERE, "data")):
        dirs.sort()
        for name in sorted(fnames):
            path = os.path.join(root, name)
            rel = os.path.relpath(path, HERE).replace(os.sep, "/")
            with open(path, "rb") as f:
                files.append("%s %s" % (rel, f.read().hex()))
    with open(SRC) as f:
        src = f.read()
    if MARK in src:
        src = src[:src.index(MARK)]
    with open(SRC, "w") as f:
        f.write(src + MARK + "\n" + text_fn("inputs_text", files))


main()
