"""Appends the generated functions to mini_pg8000.kara, after the MARK line,
so the program reads only the files it writes itself:

- jobs_text() is data/jobs.txt, with ~ escaping the characters a Kara
  string literal treats specially;
- inputs_text() the server replays mk.py writes (data/files.txt lists
  them), one "<name> <hex>" a line, runs of zeros as z<n>.

Run: python3 -I -B gen_kara.py"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
MARK = "\n// Generated by gen_kara.py from data/.\n"
SRC = os.path.join(HERE, "mini_pg8000.kara")


def text_fn(name, lines, chunk=2000):
    out = ["fn %s() -> String {" % name, "    let mut s = String.new();"]
    buf = ""
    for ln in lines:
        assert all(32 <= ord(c) < 127 and c not in '"\\{}' for c in ln), ln
        buf += ln + "\\n"
        if len(buf) >= chunk:
            out.append('    s.push_str("%s");' % buf)
            buf = ""
    if buf:
        out.append('    s.push_str("%s");' % buf)
    out.append("    s")
    out.append("}")
    return "\n".join(out) + "\n"


def esc(text):
    for a, b in [('~', '~t'), ('\\', '~b'), ('"', '~q'), ('{', '~o'), ('}', '~c')]:
        text = text.replace(a, b)
    return text


def rle_hex(b):
    out = []
    i = 0
    while i < len(b):
        j = i
        while j < len(b) and b[j] == 0:
            j += 1
        if j - i >= 8:
            out.append("z%d." % (j - i))
            i = j
        else:
            out.append("%02x" % b[i])
            i += 1
    return "".join(out)


def main():
    with open(os.path.join(HERE, "data", "jobs.txt")) as f:
        jobs = [esc(j) for j in f.read().split("\n") if j]
    with open(os.path.join(HERE, "data", "files.txt")) as f:
        names = [ln for ln in f.read().split("\n") if ln.endswith(".bin")]
    files = []
    for name in names:
        with open(os.path.join(HERE, "data", name), "rb") as f:
            files.append("%s %s" % (name, rle_hex(f.read())))
    with open(SRC) as f:
        src = f.read()
    if MARK in src:
        src = src[:src.index(MARK)]
    gen = [text_fn("jobs_text", jobs), text_fn("inputs_text", files)]
    with open(SRC, "w") as f:
        f.write(src + MARK + "\n" + "\n".join(gen))
    print("%d jobs, %d files" % (len(jobs), len(files)))


main()
