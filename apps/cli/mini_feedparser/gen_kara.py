#!/usr/bin/env python3
"""Appends the generated functions to mini_feedparser.kara, after the MARK
line, so the kata reads only the files it writes itself: jobs_text() is
data/jobs.txt, one hex line a job, and inputs_text() the input files mk.py
writes (data/files.txt lists them), one "<path> <hex>" a line, with every
run of eight or more zero bytes written as "z<count>." to keep the
compound documents' padding short.

Run: python3 -I -B gen_kara.py"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
MARK = "\n// Generated by gen_kara.py from data/jobs.txt.\n"
SRC = os.path.join(HERE, "mini_feedparser.kara")


def text_fn(name, lines, chunk=2000):
    out = ["fn %s() -> String {" % name, "    let mut s = String.new();"]
    buf = ""
    for ln in lines:
        assert all(32 <= ord(c) < 127 and c not in '"\\{}' for c in ln), ln
        buf += ln + "\\n"
        if len(buf) >= chunk:
            out.append('    s.push_str("%s");' % buf)
            buf = ""
    if buf:
        out.append('    s.push_str("%s");' % buf)
    out.append("    s")
    out.append("}")
    return "\n".join(out) + "\n"


def rle_hex(b):
    out = []
    i = 0
    while i < len(b):
        j = i
        while j < len(b) and b[j] == 0:
            j += 1
        if j - i >= 8:
            out.append("z%d." % (j - i))
            i = j
        else:
            out.append("%02x" % b[i])
            i += 1
    return "".join(out)


def word_fn(name, words):
    return text_fn(name, [" ".join(words[i:i + 12]) for i in range(0, len(words), 12)])


def tables():
    # The library's own tables, read from the vendored feedparser.
    import sys
    sys.path.insert(0, os.path.join(HERE, "vendor"))
    import html.entities
    from feedparser.sanitizer import _HTMLSanitizer as S
    from feedparser.html import _cp1252
    from feedparser.mixin import _FeedParserMixin as M
    from feedparser.urls import ACCEPTABLE_URI_SCHEMES
    out = []
    out.append(word_fn("tbl_entities", ["%s=%d" % kv for kv in html.entities.name2codepoint.items()]))
    out.append(word_fn("tbl_cp1252", [str(ord(_cp1252[c])) if c in _cp1252 else "-1" for c in range(128, 160)]))
    out.append(text_fn("tbl_namespaces", ["%s %s" % (k, v or "-") for k, v in M.namespaces.items() if k]))
    out.append(word_fn("tbl_elements", sorted(S.acceptable_elements)))
    out.append(word_fn("tbl_attributes", sorted(S.acceptable_attributes)))
    out.append(word_fn("tbl_css_properties", sorted(S.acceptable_css_properties)))
    out.append(word_fn("tbl_css_keywords", sorted(S.acceptable_css_keywords)))
    out.append(word_fn("tbl_schemes", list(ACCEPTABLE_URI_SCHEMES)))
    assert set(S.unacceptable_elements_with_end_tag) == {"script", "applet", "style"}
    return out


def main():
    with open(os.path.join(HERE, "data", "jobs.txt"), "rb") as f:
        jobs = f.read().split(b"\n")
    parts = [text_fn("jobs_text", [j.hex() for j in jobs if j])]
    files = []
    with open(os.path.join(HERE, "data", "files.txt")) as f:
        inputs = [ln for ln in f.read().split("\n") if ln]
    for name in inputs:
        with open(os.path.join(HERE, "data", name), "rb") as f:
            files.append("%s %s" % (name, rle_hex(f.read())))
    parts.append(text_fn("inputs_text", files))
    parts.extend(tables())
    with open(SRC) as f:
        src = f.read()
    if MARK in src:
        src = src[:src.index(MARK)]
    with open(SRC, "w") as f:
        f.write(src + MARK + "\n" + "\n".join(parts))


main()
