#!/usr/bin/env python3
"""Appends the generated functions to mini_texttable.kara, after the MARK
line, so the kata reads no files at run time: jobs_text() is data/jobs.tsv
verbatim, and width_text() lists the code point ranges that texttable's
fallback uchar_width() measures from unicodedata: "w lo hi" where
east_asian_width() is W or F (width 2), and "z lo hi" where combining() is
not 0 (width 0), in hex, and "d lo hi" for each run of decimal digits
whose values count up from 0 at lo (which float() and int() read as
ASCII digits).

Run: python3 -I -B gen_kara.py"""
import os
import unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))
MARK = "\n// Generated by gen_kara.py from data/jobs.tsv.\n"
SRC = os.path.join(HERE, "mini_texttable.kara")


def esc(s):
    out = []
    for c in s:
        if c == "\\":
            out.append("\\\\")
        elif c == '"':
            out.append('\\"')
        elif c == "\t":
            out.append("\\t")
        elif c == "\n":
            out.append("\\n")
        elif ord(c) < 32 or ord(c) == 127:
            out.append("\\x%02x" % ord(c))
        else:
            out.append(c)
    return "".join(out)


def text_fn(name, lines, chunk):
    out = ["fn %s() -> String {" % name, "    let mut s = String.new();"]
    buf = ""
    for ln in lines:
        buf += esc(ln + "\n")
        if len(buf) >= chunk:
            out.append('    s.push_str("%s");' % buf)
            buf = ""
    if buf:
        out.append('    s.push_str("%s");' % buf)
    out.append("    s")
    out.append("}")
    return "\n".join(out) + "\n"


def ranges(tag, pred):
    out = []
    start = None
    for cp in range(0x110001):
        hit = cp < 0x110000 and pred(chr(cp))
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append("%s %x %x" % (tag, start, cp - 1))
            start = None
    return out


def width_lines():
    def wide(c):
        return unicodedata.east_asian_width(c) in "WF"

    def zero(c):
        return not wide(c) and unicodedata.combining(c) != 0

    digits = []
    for cp in range(0x110000):
        if unicodedata.decimal(chr(cp), None) == 0:
            hi = cp
            while unicodedata.decimal(chr(hi + 1), None) == hi + 1 - cp:
                hi += 1
            digits.append("d %x %x" % (cp, hi))
    return ranges("w", wide) + ranges("z", zero) + digits


def main():
    with open(os.path.join(HERE, "data", "jobs.tsv"), encoding="utf-8") as fh:
        jobs = [ln for ln in fh.read().split("\n") if ln]
    with open(SRC, encoding="utf-8") as fh:
        src = fh.read()
    if MARK in src:
        src = src[: src.index(MARK)]
    src = src.rstrip("\n") + "\n" + MARK
    src += text_fn("jobs_text", jobs, 1)
    src += "\n" + text_fn("width_text", width_lines(), 1000)
    with open(SRC, "w", encoding="utf-8") as fh:
        fh.write(src)


main()
