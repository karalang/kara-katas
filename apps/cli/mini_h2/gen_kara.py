# Prints the data section at the end of mini_h2.kara: data/jobs.txt as
# mk.py wrote it, and the two state machines' transition tables, read off
# the vendored h2 (H2StreamStateMachine's _transitions and
# H2ConnectionStateMachine._transitions).
#
# Run: python3 -I -B gen_kara.py > data.kara
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "vendor"))

from h2 import connection, stream  # noqa: E402

FUNCS = [
    "request_sent", "response_sent", "request_received", "response_received", "data_received",
    "window_updated", "stream_half_closed", "stream_ended", "stream_reset", "send_new_pushed_stream",
    "recv_new_pushed_stream", "send_push_promise", "recv_push_promise", "send_end_stream",
    "send_reset_stream", "reset_stream_on_error", "recv_on_closed_stream", "send_on_closed_stream",
    "recv_push_on_closed_stream", "send_push_on_closed_stream", "send_informational_response",
    "recv_informational_response", "recv_alt_svc", "send_alt_svc",
]


def lit(s):
    out = []
    for c in s:
        o = ord(c)
        if c == "\\":
            out.append("\\\\")
        elif c == '"':
            out.append('\\"')
        elif o < 32 or o >= 127:
            out.append(f"\\u{{{o:x}}}")
        else:
            out.append(c)
    return '"' + "".join(out) + '"'


def chunked(name, text, per=100):
    pieces = [text[i:i + 2000] for i in range(0, len(text), 2000)] or [""]
    groups = [pieces[i:i + per] for i in range(0, len(pieces), per)]
    out = []
    for gi, g in enumerate(groups):
        out.append(f"fn {name}_{gi}(out: mut ref String) {{")
        for p in g:
            out.append(f"    out.push_str({lit(p)});")
        out.append("}")
        out.append("")
    out.append(f"fn {name}() -> String {{")
    out.append("    let mut out = String.new();")
    for gi in range(len(groups)):
        out.append(f"    {name}_{gi}(mut out);")
    out.append("    out")
    out.append("}")
    out.append("")
    return "\n".join(out)


def main():
    print("// ---------------------------------------------------------------- data")
    print("// Generated by gen_kara.py.")
    print()
    with open(os.path.join(HERE, "data", "jobs.txt"), encoding="utf-8") as fh:
        print(chunked("jobs_text", fh.read()))

    print("// H2StreamStateMachine's _transitions: (state, input) to (callback, target).")
    print("// The callback is FUNCS' index plus one, 0 for none; -1 means no transition.")
    print("fn stream_transition(state: i64, input: i64) -> (i64, i64) {")
    print("    match state * 100 + input {")
    for (st, inp), (fn, target) in stream._transitions.items():
        f = 0 if fn is None else FUNCS.index(fn.__name__) + 1
        print(f"        {int(st) * 100 + inp.value} => ({f}, {int(target)}),")
    print("        _ => (-1, -1),")
    print("    }")
    print("}")
    print()
    print("// H2ConnectionStateMachine._transitions: (state, input) to target, -1 for none.")
    print("fn conn_transition(state: i64, input: i64) -> i64 {")
    print("    match state * 100 + input {")
    for (st, inp), (fn, target) in connection.H2ConnectionStateMachine._transitions.items():
        assert fn is None
        print(f"        {st.value * 100 + inp.value} => {target.value},")
    print("        _ => -1,")
    print("    }")
    print("}")


main()
