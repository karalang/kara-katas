#!/usr/bin/env python3
"""Writes data/: the binary files the jobs read, and data/jobs.txt."""
import gzip, io, math, os, struct, wave, zipfile

os.makedirs("data", exist_ok=True)

# A 16-bit stereo WAV, 24 frames at 8000 Hz, written by Python's wave module.
with wave.open("data/tone.wav", "wb") as w:
    w.setnchannels(2)
    w.setsampwidth(2)
    w.setframerate(8000)
    frames = b"".join(
        struct.pack("<hh", int(12000 * math.sin(i / 3)), int(-9000 * math.cos(i / 5)))
        for i in range(24))
    w.writeframes(frames)

# A gzip member with a fixed mtime and a file name.
buf = io.BytesIO()
with gzip.GzipFile(filename="notes.txt", mode="wb", fileobj=buf, mtime=1700000000) as g:
    g.write(b"struct packs and unpacks C structs\n" * 3)
open("data/notes.txt.gz", "wb").write(buf.getvalue())

# A zip with two stored members and fixed timestamps.
with zipfile.ZipFile("data/pair.zip", "w", zipfile.ZIP_STORED) as z:
    z.writestr(zipfile.ZipInfo("a.txt", (2024, 2, 29, 13, 45, 10)), b"alpha\n")
    z.writestr(zipfile.ZipInfo("dir/b.txt", (1999, 12, 31, 23, 59, 58)), b"bravo bravo\n")

# Sensor records: <IhhfB3x (station id, temp*100, humidity*10, pressure, flags).
recs = [(1001, 2315, 455, 1013.25, 1), (1002, -415, 873, 998.5, 0),
        (1003, 0, 1000, 1020.0, 3), (2001, 3999, 120, 950.125, 2),
        (2002, -2731, 0, 0.0, 255)]
open("data/sensors.bin", "wb").write(b"".join(struct.pack("<IhhfB3x", *r) for r in recs))

# A big-endian header: magic, version, count, then count (u16 len, bytes) names.
names = [b"eth0", b"lo", b"wlan0", b""]
body = b"".join(struct.pack(">H", len(n)) + n for n in names)
open("data/ifaces.bin", "wb").write(struct.pack(">4sBxH", b"IFAC", 2, len(names)) + body)

