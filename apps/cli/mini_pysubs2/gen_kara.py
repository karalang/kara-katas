#!/usr/bin/env python3
"""Appends the generated functions to mini_pysubs2.kara, after the MARK
line, so the kata reads no files at run time: jobs_text() is data/jobs.tsv
verbatim, and help_text() and usage_text() are what the vendored CLI's
argparse parser prints for -h and before an error, at 80 columns.

Run: python3 -I -B gen_kara.py"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
MARK = "\n// Generated by gen_kara.py from data/jobs.tsv.\n"
SRC = os.path.join(HERE, "mini_pysubs2.kara")

os.environ["COLUMNS"] = "80"
sys.path.insert(0, os.path.join(HERE, "vendor"))
from pysubs2.cli import Pysubs2CLI  # noqa: E402


def esc(s):
    out = []
    for c in s:
        if c == "\\":
            out.append("\\\\")
        elif c == '"':
            out.append('\\"')
        elif c == "{":
            out.append("{")
        elif c == "\t":
            out.append("\\t")
        elif c == "\n":
            out.append("\\n")
        elif ord(c) < 32 or ord(c) == 127:
            out.append("\\x%02x" % ord(c))
        else:
            out.append(c)
    return "".join(out)


def text_fn(name, lines, chunk):
    out = ["fn %s() -> String {" % name, "    let mut s = String.new();"]
    buf = ""
    for ln in lines:
        buf += esc(ln + "\n")
        if len(buf) >= chunk:
            out.append('    s.push_str("%s");' % buf)
            buf = ""
    if buf:
        out.append('    s.push_str("%s");' % buf)
    out.append("    s")
    out.append("}")
    return "\n".join(out) + "\n"


def main():
    with open(os.path.join(HERE, "data", "jobs.tsv"), encoding="utf-8") as fh:
        jobs = [ln for ln in fh.read().split("\n") if ln]
    parser = Pysubs2CLI().parser
    help_lines = parser.format_help().split("\n")[:-1]
    usage_lines = parser.format_usage().split("\n")[:-1]
    with open(SRC, encoding="utf-8") as fh:
        src = fh.read()
    if MARK in src:
        src = src[: src.index(MARK)]
    src = src.rstrip("\n") + "\n" + MARK
    src += text_fn("jobs_text", jobs, 1)
    src += "\n" + text_fn("help_text", help_lines, 1000)
    src += "\n" + text_fn("usage_text", usage_lines, 1000)
    with open(SRC, "w", encoding="utf-8") as fh:
        fh.write(src)


main()
