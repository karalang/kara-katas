"""Writes data/jobs.tsv: the subtitle files of a film festival's subtitle
desk, and the jobs its tools run over them.

A job line is: name, files, dirs, then one op per field. Files are
"name=hex" pairs (comma-separated, "-" for none) and dirs a comma-separated
list ("-" for none). An op is words separated by spaces; "h:<hex>" is a
UTF-8 string and "-" is None.

Run: python3 -s -P -B mk.py"""
