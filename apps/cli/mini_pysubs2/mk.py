def hx(s):
    return "h:" + s.encode("utf-8").hex()


def files(*names):
    if not names:
        return "-"
    return ",".join(n + "=" + F[n].hex() for n in names)


JOBS = []


def job(name, names, dirs, *ops):
    JOBS.append("\t".join([name, files(*names), ",".join(dirs) if dirs else "-"] + list(ops)))


