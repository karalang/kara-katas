#!/usr/bin/env python3
"""Appends the generated functions to mini_zxcvbn.kara, after the MARK
line, so the kata reads only the files it writes itself: jobs_text() is
data/jobs.tsv, one hex line a job; inputs_text() the small input files
(data/files.txt lists them), one "<path> <hex>" a line; and freq_text()
data/frequency_lists.tsv as plain text, since its 700 KB of lower-case
words would double in hex.

Run: python3 -I -B gen_kara.py"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
MARK = "\n// Generated by gen_kara.py from data/jobs.tsv.\n"
SRC = os.path.join(HERE, "mini_zxcvbn.kara")
TEXT_FILES = ["frequency_lists.tsv"]


def text_fn(name, lines, chunk=2000):
    out = ["fn %s() -> String {" % name, "    let mut s = String.new();"]
    buf = ""
    for ln in lines:
        assert all(32 <= ord(c) < 127 and c not in '"\\{}' for c in ln), ln
        buf += ln + "\\n"
        if len(buf) >= chunk:
            out.append('    s.push_str("%s");' % buf)
            buf = ""
    if buf:
        out.append('    s.push_str("%s");' % buf)
    out.append("    s")
    out.append("}")
    return "\n".join(out) + "\n"


def plain_fn(name, text, chunk=2000):
    """A function returning `text`, which holds only printable ASCII, tabs
    and newlines, with no quote, backslash or brace."""
    assert all((32 <= ord(c) < 127 and c not in '"\\{}') or c in "\t\n"
               for c in text)
    out = ["fn %s() -> String {" % name, "    let mut s = String.new();"]
    for k in range(0, len(text), chunk):
        piece = text[k:k + chunk].replace("\t", "\\t").replace("\n", "\\n")
        out.append('    s.push_str("%s");' % piece)
    out.append("    s")
    out.append("}")
    return "\n".join(out) + "\n"


def main():
    with open(os.path.join(HERE, "data", "jobs.tsv"), "rb") as f:
        jobs = f.read().split(b"\n")
    parts = [text_fn("jobs_text", [j.hex() for j in jobs if j])]
    files = []
    with open(os.path.join(HERE, "data", "files.txt")) as f:
        inputs = [ln for ln in f.read().split("\n") if ln]
    for name in inputs:
        if name in TEXT_FILES:
            continue
        with open(os.path.join(HERE, "data", name), "rb") as f:
            files.append("%s %s" % (name, f.read().hex()))
    parts.append(text_fn("inputs_text", files))
    with open(os.path.join(HERE, "data", "frequency_lists.tsv")) as f:
        parts.append(plain_fn("freq_text", f.read()))
    with open(SRC) as f:
        src = f.read()
    if MARK in src:
        src = src[:src.index(MARK)]
    with open(SRC, "w") as f:
        f.write(src + MARK + "\n" + "\n".join(parts))


main()
