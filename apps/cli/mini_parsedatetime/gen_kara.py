#!/usr/bin/env python3
"""Appends the generated functions to mini_parsedatetime.kara, after the
MARK line, so the kata reads only the files it writes itself.

- regex_text(): every regular expression the vendored library uses, one
  "<name> <flags> <hex>" a line. For each locale the port knows, the
  Constants object's own sources (cre_source, compiled with its
  re_option, IGNORECASE | VERBOSE) as "<locale>.<CRE_NAME>"; and the ones
  the Calendar passes to re.sub(), re.search() and re.split() itself, as
  "<function>.<n>", read off by running each function once with re
  wrapped so it records what it is given.
- locale_text(): each locale's tables after Constants() has filled them
  in, one "<locale> <key> <kind> <items>" a line; strings are hex.
- unicode_text(): from Python's unicodedata (Unicode 15.1), the runs of
  code points that are alphanumeric ("W"), decimal digits ("9") and
  whitespace ("S"), for \\w, \\b, \\d and \\s.
- jobs_text(): data/jobs.tsv, and inbox_text(): data/inbox/ and
  data/todo.txt as mk.py writes them, each "<name> <hex>".

Run: python3 -I -B gen_kara.py"""
import os
import re
import sys
import time
import warnings

warnings.simplefilter("ignore")
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "vendor"))
import parsedatetime as pdt  # noqa: E402

MARK = "\n// Generated by gen_kara.py from data/jobs.tsv.\n"
SRC = os.path.join(HERE, "mini_parsedatetime.kara")
LOCALES = ["en_US", "en_AU"]

SEEN = []


class Recorder:
    def __getattr__(self, name):
        return getattr(re, name)

    def _note(self, pattern, flags):
        func = sys._getframe(2).f_code.co_name
        key = (func, pattern, int(flags))
        if key not in SEEN:
            SEEN.append(key)

    def compile(self, pattern, flags=0):
        self._note(pattern, flags)
        return re.compile(pattern, flags)

    def sub(self, pattern, repl, string, count=0, flags=0):
        self._note(pattern, flags)
        return re.sub(pattern, repl, string, count=count, flags=flags)

    def search(self, pattern, string, flags=0):
        self._note(pattern, flags)
        return re.search(pattern, string, flags)

    def split(self, pattern, string, maxsplit=0, flags=0):
        self._note(pattern, flags)
        return re.split(pattern, string, maxsplit=maxsplit, flags=flags)


def h(s):
    return s.encode("utf-8").hex() or "-"


def regexes():
    out = []
    for loc in LOCALES:
        c = pdt.Constants(loc)
        for name in sorted(c.cre_source):
            out.append("%s.%s %d %s" % (loc, name, c.re_option, h(c.cre_source[name])))
    pdt.re = Recorder()
    try:
        cal = pdt.Calendar(version=pdt.VERSION_CONTEXT_STYLE)
        src = (2026, 10, 23, 14, 30, 15, 4, 296, 0)
        cal.parse("x", src)
        cal.nlp("x")
        cal.evalRanges("4-5pm", src)
        cal._convertUnitAsWords("one")
    finally:
        pdt.re = re
    count = {}
    for func, pattern, flags in SEEN:
        if func in ("__init__", "__getattr__", "re_join"):
            continue
        n = count.get(func, 0)
        count[func] = n + 1
        out.append("%s.%d %d %s" % (func, n, flags, h(pattern)))
    return out


def strs(items):
    return ",".join(h(x) for x in items) or "-"


def locale_lines():
    out = []
    for loc in LOCALES:
        c = pdt.Constants(loc)
        lc = c.locale
        for key in ["Months", "shortMonths", "Weekdays", "shortWeekdays", "dp_order",
                    "meridian", "dateSep", "timeSep"]:
            out.append("%s %s L %s" % (loc, key, strs(getattr(lc, key))))
        out.append("%s ignore L %s" % (loc, strs(lc.ignore)))
        out.append("%s now L %s" % (loc, strs(lc.re_values["now"])))
        out.append("%s am L %s" % (loc, strs(c.am)))
        out.append("%s pm L %s" % (loc, strs(c.pm)))
        out.append("%s usesMeridian B %d" % (loc, 1 if lc.usesMeridian else 0))
        out.append("%s decimal_mark L %s" % (loc, strs([lc.decimal_mark])))
        for key in ["numbers", "small", "magnitude", "Modifiers", "dayOffsets",
                    "WeekdayOffsets", "MonthOffsets"]:
            d = getattr(lc, key)
            items = []
            for k, v in d.items():
                # magnitudes past 10**18 do not fit an i64 (see README)
                items.append("%s:%d" % (h(k), v if abs(v) <= 10 ** 18 else -1))
            out.append("%s %s M %s" % (loc, key, ",".join(items)))
        for k, values in lc.units.items():
            out.append("%s units.%s L %s" % (loc, k, strs(values)))
        items = []
        for k, v in lc.re_sources.items():
            items.append("%s:%d:%d:%d" % (h(k), v.get("hr", -1), v.get("mn", -1), v.get("sec", -1)))
        out.append("%s re_sources S %s" % (loc, ",".join(items)))
    return out


def runs(tag, pred):
    out, start = [], None
    for cp in range(0x110001):
        v = cp < 0x110000 and pred(chr(cp))
        if v and start is None:
            start = cp
        elif not v and start is not None:
            out.append("%s%x %x" % (tag, start, cp - 1))
            start = None
    return out


def text_fn(name, lines, chunk=2000):
    out = ["fn %s() -> String {" % name, "    let mut s = String.new();"]
    buf = ""
    for ln in lines:
        assert all(32 <= ord(c) < 127 and c not in '"\\{}' for c in ln.replace("\t", " ")), ln
        buf += ln.replace("\t", "\\t") + "\\n"
        if len(buf) >= chunk:
            out.append('    s.push_str("%s");' % buf)
            buf = ""
    if buf:
        out.append('    s.push_str("%s");' % buf)
    out.append("    s")
    out.append("}")
    return "\n".join(out) + "\n"


def main():
    parts = [text_fn("regex_text", regexes()), text_fn("locale_text", locale_lines())]
    uni = (runs("W", lambda c: c.isalnum()) + runs("9", lambda c: c.isdecimal())
           + runs("S", lambda c: c.isspace()))
    parts.append(text_fn("unicode_text", uni))
    with open(os.path.join(HERE, "data", "jobs.tsv"), "rb") as f:
        jobs = f.read().decode("utf-8").split("\n")
    parts.append(text_fn("jobs_text", [j.encode("utf-8").hex() for j in jobs if j]))
    files = []
    inbox = os.path.join(HERE, "data", "inbox")
    for name in sorted(os.listdir(inbox)):
        with open(os.path.join(inbox, name), "rb") as f:
            files.append("inbox/%s %s" % (name, f.read().hex() or "-"))
    with open(os.path.join(HERE, "data", "todo.txt"), "rb") as f:
        files.append("todo.txt %s" % f.read().hex())
    parts.append(text_fn("inbox_text", files))
    with open(SRC) as f:
        src = f.read()
    if MARK in src:
        src = src[:src.index(MARK)]
    with open(SRC, "w") as f:
        f.write(src + MARK + "\n" + "\n".join(parts))


main()
