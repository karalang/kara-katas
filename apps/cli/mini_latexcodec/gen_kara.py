#!/usr/bin/env python3
"""Appends the generated functions to mini_latexcodec.kara, after the MARK
line, so the kata reads no files at run time: jobs_text() is data/jobs.tsv
verbatim, and table_text() is the vendored latexcodec/table.txt with each
line's Unicode character names resolved to code points (in hex,
comma-separated), as load_unicode_latex_table() resolves them with
unicodedata.lookup.

Run: python3 -I -B gen_kara.py"""
import os
import unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))
MARK = "\n// Generated by gen_kara.py from data/jobs.tsv.\n"
SRC = os.path.join(HERE, "mini_latexcodec.kara")


def esc(s):
    out = []
    for c in s:
        if c == "\\":
            out.append("\\\\")
        elif c == '"':
            out.append('\\"')
        elif c == "\t":
            out.append("\\t")
        elif c == "\n":
            out.append("\\n")
        elif ord(c) < 32 or ord(c) == 127:
            out.append("\\x%02x" % ord(c))
        else:
            out.append(c)
    return "".join(out)


def text_fn(name, lines, chunk):
    out = ["fn %s() -> String {" % name, "    let mut s = String.new();"]
    buf = ""
    for ln in lines:
        buf += esc(ln + "\n")
        if len(buf) >= chunk:
            out.append('    s.push_str("%s");' % buf)
            buf = ""
    if buf:
        out.append('    s.push_str("%s");' % buf)
    out.append("    s")
    out.append("}")
    return "\n".join(out) + "\n"


def table_lines():
    path = os.path.join(HERE, "vendor", "latexcodec", "table.txt")
    out = []
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            marker, names, latex = line.rstrip("\r\n").split("\t")
            assert latex.isascii(), latex
            cps = ",".join("%x" % ord(unicodedata.lookup(n)) for n in names.split(","))
            out.append(marker + "\t" + cps + "\t" + latex)
    return out


def main():
    with open(os.path.join(HERE, "data", "jobs.tsv"), encoding="utf-8") as fh:
        jobs = [ln for ln in fh.read().split("\n") if ln]
    with open(SRC, encoding="utf-8") as fh:
        src = fh.read()
    if MARK in src:
        src = src[: src.index(MARK)]
    src = src.rstrip("\n") + "\n" + MARK
    src += text_fn("jobs_text", jobs, 1)
    src += "\n" + text_fn("table_text", table_lines(), 1000)
    with open(SRC, "w", encoding="utf-8") as fh:
        fh.write(src)


main()
