#!/usr/bin/env python3
"""Appends the generated functions to mini_boolean.kara, after the MARK
line, so the kata reads only the files it writes itself: jobs_text() is
data/jobs.tsv and inputs_text() the licence and access files mk.py
writes, one "<path> <hex>" a line.

Run: python3 -I -B gen_kara.py"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
MARK = "\n// Generated by gen_kara.py from data/jobs.tsv.\n"
SRC = os.path.join(HERE, "mini_boolean.kara")


def text_fn(name, lines, chunk=2000):
    out = ["fn %s() -> String {" % name, "    let mut s = String.new();"]
    buf = ""
    for ln in lines:
        assert all(32 <= ord(c) < 127 and c not in '"\\{}' for c in ln), ln
        buf += ln + "\\n"
        if len(buf) >= chunk:
            out.append('    s.push_str("%s");' % buf)
            buf = ""
    if buf:
        out.append('    s.push_str("%s");' % buf)
    out.append("    s")
    out.append("}")
    return "\n".join(out) + "\n"


def main():
    with open(os.path.join(HERE, "data", "jobs.tsv"), "rb") as f:
        jobs = f.read().split(b"\n")
    parts = [text_fn("jobs_text", [j.hex() for j in jobs if j])]
    files = []
    for sub in ("licences", "access"):
        d = os.path.join(HERE, "data", sub)
        for name in sorted(os.listdir(d)):
            with open(os.path.join(d, name), "rb") as f:
                files.append("%s/%s %s" % (sub, name, f.read().hex()))
    parts.append(text_fn("inputs_text", files))
    with open(SRC) as f:
        src = f.read()
    if MARK in src:
        src = src[:src.index(MARK)]
    with open(SRC, "w") as f:
        f.write(src + MARK + "\n" + "\n".join(parts))


main()
