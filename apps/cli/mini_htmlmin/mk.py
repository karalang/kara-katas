def esc(s):
    return s.replace("\\", "\\\\").replace("\t", "\\t").replace("\n", "\\n")


def main():
    for name, text in FILES.items():
        path = os.path.join(DATA, name)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="") as fh:
            fh.write(text)
    with open(os.path.join(DATA, "patterns.txt"), "w", encoding="utf-8") as fh:
        for name, rx in PATTERNS:
            fh.write("%s %d %s\n" % (name, rx.flags,
                                     rx.pattern.encode("utf-8").hex()))
    jobs = []
    jobs.append("# pages, with each option set")
    for page in PAGES:
        for opts in OPTION_SETS:
            jobs.append("\t".join(["minify", page] + opts))
    jobs.append("# snippets")
    for html, opts in SNIPPETS:
        jobs.append("\t".join(["snippet", html] + opts))
    jobs.append("# fed in chunks to one Minifier")
    for page, size, opts in CHUNKS:
        jobs.append("\t".join(["chunks", page, str(size)] + opts))
    jobs.append("# escaping")
    for e in ESCAPES:
        jobs.append("\t".join([e[0], esc(e[1])] + list(e[2:])))
