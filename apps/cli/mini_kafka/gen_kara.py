"""Appends the generated functions to mini_kafka.kara, after the MARK line,
so the program reads only the files it writes itself:

- jobs_text() is data/jobs.txt and recsets_text() data/recsets.txt;
- inputs_text() the binary files mk.py writes (data/files.txt lists them), one
  "<name> <hex>" a line, runs of zeros as z<n>.;
- schemas_text() the request and response schemas of the five APIs the
  sessions use, every version, read from the vendored classes, so the
  port's encoder, decoder and repr work from what kafka-python declares
  (including the fields Schema's zip() drops from ProduceResponse_v8);
- errors_text() kafka.errors.kafka_errors, the table for_code() reads.

Run: python3 -I -B gen_kara.py"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import kstub  # noqa: E402

kstub.install()

from kafka.errors import kafka_errors  # noqa: E402
from kafka.protocol import api_versions, fetch, find_coordinator, metadata, produce  # noqa: E402
from kafka.protocol import types as T  # noqa: E402

MARK = "\n// Generated by gen_kara.py from data/ and the vendored kafka-python.\n"
SRC = os.path.join(HERE, "mini_kafka.kara")

APIS = [
    ('ApiVersions', api_versions.ApiVersionsRequest),
    ('Metadata', metadata.MetadataRequest),
    ('Produce', produce.ProduceRequest),
    ('Fetch', fetch.FetchRequest),
    ('FindCoordinator', find_coordinator.FindCoordinatorRequest),
]

PRIMS = [(T.Int8, 'i8'), (T.Int16, 'i16'), (T.Int32, 'i32'), (T.Int64, 'i64'),
         (T.Boolean, 'bool'), (T.Bytes, 'bytes'), (T.CompactBytes, 'cbytes'),
         (T.TaggedFields, 'tags'), (T.UnsignedVarInt32, 'uv32')]


def ty(t):
    # Order matters: CompactString is a String, CompactArray an Array.
    if isinstance(t, T.CompactString):
        return 'cstr'
    if isinstance(t, T.String):
        assert t.encoding == 'utf-8'
        return 'str'
    if isinstance(t, T.CompactArray):
        return 'C<%s>' % ty(t.array_of)
    if isinstance(t, T.Array):
        return 'A<%s>' % ty(t.array_of)
    if isinstance(t, T.Schema):
        return 'S(%s)' % ' '.join('%s:%s' % (n, ty(f)) for n, f in zip(t.names, t.fields))
    for cls, name in PRIMS:
        if t is cls:
            return name
    raise ValueError('unsupported type %r' % (t,))


def text_fn(name, lines, chunk=2000):
    out = ["fn %s() -> String {" % name, "    let mut s = String.new();"]
    buf = ""
    for ln in lines:
        assert all(32 <= ord(c) < 127 and c not in '"\\{}' for c in ln), ln
        buf += ln + "\\n"
        if len(buf) >= chunk:
            out.append('    s.push_str("%s");' % buf)
            buf = ""
    if buf:
        out.append('    s.push_str("%s");' % buf)
    out.append("    s")
    out.append("}")
    return "\n".join(out) + "\n"


def esc(text):
    """Text the Kara side reads back with unesc(): ~ escapes the characters
    a string literal or an f-string would treat specially."""
    for a, b in [('~', '~t'), ('\\', '~b'), ('"', '~q'), ('{', '~o'), ('}', '~c')]:
        text = text.replace(a, b)
    return text


def rle_hex(b):
    out = []
    i = 0
    while i < len(b):
        j = i
        while j < len(b) and b[j] == 0:
            j += 1
        if j - i >= 8:
            out.append("z%d." % (j - i))
            i = j
        else:
            out.append("%02x" % b[i])
            i += 1
    return "".join(out)


def main():
    with open(os.path.join(HERE, "data", "jobs.txt")) as f:
        jobs = [esc(j) for j in f.read().split("\n") if j]
    with open(os.path.join(HERE, "data", "recsets.txt")) as f:
        recsets = f.read().split("\n")
    with open(os.path.join(HERE, "data", "files.txt")) as f:
        names = [ln for ln in f.read().split("\n") if ln.endswith('.bin')]
    files = []
    for name in names:
        with open(os.path.join(HERE, "data", name), "rb") as f:
            files.append("%s %s" % (name, rle_hex(f.read())))
    schemas = []
    for api, versions in APIS:
        for v, req in enumerate(versions):
            resp = req.RESPONSE_TYPE
            assert req.API_VERSION == v and resp.API_VERSION == v
            base = int(issubclass(resp, api_versions.BaseApiVersionsResponse))
            schemas.append('req %s %d %d %d %s %s' % (api, v, req.API_KEY, int(req.FLEXIBLE_VERSION),
                                                       req.__name__, ty(req.SCHEMA)))
            schemas.append('resp %s %d %d %d %s %s' % (api, v, resp.API_KEY, base,
                                                        resp.__name__, ty(resp.SCHEMA)))
    errors = []
    for errno in sorted(k for k in kafka_errors if k is not None):
        cls = kafka_errors[errno]
        errors.append('%d|%s|%s|%d|%d' % (errno, cls.__name__, cls.message, int(cls.retriable),
                                          int(cls.invalid_metadata)))
    with open(SRC) as f:
        src = f.read()
    if MARK in src:
        src = src[:src.index(MARK)]
    gen = [text_fn("jobs_text", jobs), text_fn("recsets_text", recsets),
           text_fn("inputs_text", files), text_fn("schemas_text", schemas),
           text_fn("errors_text", errors)]
    with open(SRC, "w") as f:
        f.write(src + MARK + "\n" + "\n".join(gen))
    print("%d jobs, %d files, %d schemas, %d errors" % (len(jobs), len(files), len(schemas), len(errors)))


main()
