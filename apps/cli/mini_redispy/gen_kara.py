"""Appends jobs_text() to mini_redispy.kara, after the MARK line: the text
of data/jobs.txt, so the program reads only what it carries itself.

Run: python3 -I -B gen_kara.py"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
MARK = "\n// Generated by gen_kara.py from data/jobs.txt.\n"
SRC = os.path.join(HERE, "mini_redispy.kara")


def esc(text):
    """Text the Kara side reads back with unesc(): ~ escapes the characters
    a string literal or an f-string would treat specially."""
    for a, b in [('~', '~t'), ('\\', '~b'), ('"', '~q'), ('{', '~o'), ('}', '~c')]:
        text = text.replace(a, b)
    return text


def text_fn(name, lines, chunk=2000):
    out = ["fn %s() -> String {" % name, "    let mut s = String.new();"]
    buf = ""
    for ln in lines:
        assert all(32 <= ord(c) < 127 and c not in '"\\{}' for c in ln), ln
        buf += ln + "\\n"
        if len(buf) >= chunk:
            out.append('    s.push_str("%s");' % buf)
            buf = ""
    if buf:
        out.append('    s.push_str("%s");' % buf)
    out.append("    s")
    out.append("}")
    return "\n".join(out) + "\n"


def main():
    with open(os.path.join(HERE, "data", "jobs.txt")) as f:
        jobs = [esc(j) for j in f.read().split("\n") if j]
    with open(SRC) as f:
        src = f.read()
    if MARK in src:
        src = src[:src.index(MARK)]
    with open(SRC, "w") as f:
        f.write(src + MARK + "\n" + text_fn("jobs_text", jobs))
    print("%d job lines" % len(jobs))


main()
