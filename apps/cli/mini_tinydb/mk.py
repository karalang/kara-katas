def main():
    if os.path.isdir(DATA):
        shutil.rmtree(DATA)
    os.makedirs(DATA)
    for name, text in (("contacts.csv", CONTACTS), ("queries.tsv", QUERIES), ("updates.tsv", UPDATES)):
        with open(os.path.join(DATA, name), "w", encoding="utf-8") as f:
            f.write(text)
    with open(os.path.join(DATA, "jobs.tsv"), "w", encoding="utf-8") as f:
        for kind, text in JOBS:
            assert "\t" not in text and "\n" not in text, text
            f.write("%s\t%s\n" % (kind, text))
    n = sum(1 for k, _ in JOBS if k not in ("#", "reset"))
    print("wrote %d steps" % n)


main()
