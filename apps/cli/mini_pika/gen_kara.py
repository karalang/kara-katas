"""Appends the generated functions to mini_pika.kara, after the MARK line,
so the program reads no file of its own:

- urls_text() is data/urls.txt and sessions_text() data/sessions.txt;
- spec_text() the AMQP 0-9-1 method table read off the vendored
  pika/spec.py: each method's index, name and the fields its decode()
  reads, in order, with their kinds.

Run: python3 -I -B gen_kara.py"""
import ast
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
MARK = "\n// Generated by gen_kara.py from data/ and the vendored pika/spec.py.\n"
SRC = os.path.join(HERE, "mini_pika.kara")
FMT = {"'B'": 'o', "'>H'": 'h', "'>I'": 'l', "'>Q'": 'q'}


def spec_lines(path):
    with open(path) as f:
        tree = ast.parse(f.read())
    out = []
    for top in tree.body:
        if not isinstance(top, ast.ClassDef) or top.name == 'BasicProperties':
            continue
        for cls in top.body:
            if not isinstance(cls, ast.ClassDef):
                continue
            index = name = None
            fields = []
            for st in cls.body:
                if isinstance(st, ast.Assign) and isinstance(st.targets[0], ast.Name):
                    if st.targets[0].id == 'INDEX':
                        index = st.value.value
                    if st.targets[0].id == 'NAME':
                        name = st.value.value
                if isinstance(st, ast.FunctionDef) and st.name == 'decode':
                    for s in st.body:
                        t = ast.unparse(s)
                        m = re.match(r"self\.(\w+) = struct\.unpack_from\(('[^']+')", t)
                        if m:
                            fields.append((m.group(1), FMT[m.group(2)]))
                            continue
                        m = re.match(r"\(?self\.(\w+), offset\)? = data\.decode_short_string", t)
                        if m:
                            fields.append((m.group(1), 's'))
                            continue
                        m = re.match(r"\(?self\.(\w+), offset\)? = data\.decode_table", t)
                        if m:
                            fields.append((m.group(1), 'F'))
                            continue
                        m = re.match(r"self\.(\w+) = encoded\[offset:offset \+ length\]", t)
                        if m:
                            fields.append((m.group(1), 'S'))
                            continue
                        m = re.match(r"self\.(\w+) = \(?bit_buffer & 1 << (\d+)\)? != 0", t)
                        if m:
                            fields.append((m.group(1), 'b' if m.group(2) != '0' else 'B'))
                            continue
            out.append(('%d %s %s' % (index, name, ' '.join('%s:%s' % f for f in fields))).rstrip())
    return out


def text_fn(name, lines, chunk=2000):
    out = ["fn %s() -> String {" % name, "    let mut s = String.new();"]
    buf = ""
    for ln in lines:
        assert all(32 <= ord(c) < 127 and c not in '"\\{}' for c in ln), ln
        buf += ln + "\\n"
        if len(buf) >= chunk:
            out.append('    s.push_str("%s");' % buf)
            buf = ""
    if buf:
        out.append('    s.push_str("%s");' % buf)
    out.append("    s")
    out.append("}")
    return "\n".join(out) + "\n"


def esc(text):
    """Text the Kara side reads back with unesc(): ~ escapes the characters
    a string literal or an f-string would treat specially."""
    for a, b in [('~', '~t'), ('\\', '~b'), ('"', '~q'), ('{', '~o'), ('}', '~c')]:
        text = text.replace(a, b)
    return text


def main():
    with open(SRC) as f:
        src = f.read()
    if MARK in src:
        src = src[:src.index(MARK)]
    with open(os.path.join(HERE, "data", "urls.txt")) as f:
        urls = [esc(u) for u in f.read().splitlines()]
    with open(os.path.join(HERE, "data", "sessions.txt")) as f:
        sessions = [esc(s) for s in f.read().splitlines()]
    spec = spec_lines(os.path.join(HERE, "vendor", "pika", "spec.py"))
    gen = [text_fn("urls_text", urls), text_fn("sessions_text", sessions),
           text_fn("spec_text", spec)]
    with open(SRC, "w") as f:
        f.write(src + MARK + "\n" + "\n".join(gen))
    print("%d urls, %d session lines, %d methods" % (len(urls), len(sessions), len(spec)))


main()
