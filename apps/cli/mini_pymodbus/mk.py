# 18. a plant floor poll cycle
job("A poll cycle: an HMI reads and writes a line of eight drives over RTU")
add("server rtu multi")
for sid in range(1, 9):
    add(f"slave {sid}")
    add(f"block h seq 0=0,{regs(16, 3000)}")
    add(f"block i seq 0=0,{regs(8, 1000)}")
    add(f"block c seq 0=0,{','.join('1' if c == '1' else '0' for c in bits(8))}")
for cycle in range(3):
    for sid in range(1, 9):
        add(f"req rir 0 4 slave={sid}")
        add(f"req rc 0 4 slave={sid}")
        if (sid + cycle) % 3 == 0:
            add(f"req wr 1 {rnd(3000)} slave={sid}")
        if (sid * 7 + cycle) % 5 == 0:
            add(f"req wc 2 {rnd(2)} slave={sid}")
    add(f"req rhr 0 8 slave={1 + rnd(8)}")
    add(f"req rhr 0 2 slave=9")
for sid in range(1, 9):
    add(f"peek {sid} h 0 4")

