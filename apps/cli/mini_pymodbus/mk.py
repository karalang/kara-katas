import os

STATE = [20240611]


def rnd(n):
    STATE[0] = (STATE[0] * 1103515245 + 12345) % 2147483648
    return (STATE[0] >> 8) % n


def regs(n, top=65536):
    return ",".join(str(rnd(top)) for _ in range(n))


def bits(n):
    return "".join("1" if rnd(3) == 0 else "0" for _ in range(n))


def hexb(n):
    return "".join(f"{rnd(256):02x}" for _ in range(n))


def crc(data):
    c = 0xFFFF
    for b in data:
        c ^= b
        for _ in range(8):
            c = (c >> 1) ^ 0xA001 if c & 1 else c >> 1
    return bytes([c & 0xFF, c >> 8])


def rtu(hexstr):
    data = bytes.fromhex(hexstr)
    return (data + crc(data)).hex()


def lrc(data):
    return ((sum(data) & 0xFF) ^ 0xFF) + 1 & 0xFF


def ascii_frame(hexstr):
    data = bytes.fromhex(hexstr)
    return ":" + (data.hex() + f"{lrc(data):02x}").upper() + "~0D~0A"


def mbap(tid, pdu, uid=1, pid=0, extra=0):
    pdu = pdu.replace(" ", "")
    return f"{tid:04x}{pid:04x}{len(pdu) // 2 + 1 + extra:04x}{uid:02x}{pdu}"


