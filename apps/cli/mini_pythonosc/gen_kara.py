#!/usr/bin/env python3
r"""Appends jobs_text() to mini_pythonosc.kara: data/jobs.tsv verbatim, so
the kata reads no files at run time. Run after mk.py; idempotent.
Run: python3 -I -B gen_kara.py"""

MARK = "\n// Generated by gen_kara.py from data/jobs.tsv.\n"


def esc(s):
    out = []
    for c in s:
        if c == "\\":
            out.append("\\\\")
        elif c == '"':
            out.append('\\"')
        elif c == "\t":
            out.append("\\t")
        elif ord(c) < 0x20:
            out.append("\\x%02x" % ord(c))
        else:
            out.append(c)
    return "".join(out)


with open("data/jobs.tsv", encoding="utf-8") as fh:
    jobs = fh.read()

with open("mini_pythonosc.kara", encoding="utf-8") as fh:
    src = fh.read()
cut = src.find(MARK)
if cut != -1:
    src = src[:cut]
src = src.rstrip("\n") + "\n"

body = ["fn jobs_text() -> String {\n", "    let mut s = String.new();\n"]
for ln in jobs.split("\n"):
    if ln:
        body.append('    s.push_str("%s\\n");\n' % esc(ln))
body.append("    s\n}\n")
with open("mini_pythonosc.kara", "w", encoding="utf-8") as fh:
    fh.write(src + MARK + "".join(body))
